import { autoMovieRenderDigest } from "../../../../packages/engine/src/render/autoMovieRenderDigest";
import { canonicalizeAutoMovieJson } from "../../../../packages/engine/src/text/canonicalizeAutoMovieJson";
import { TestValidator } from "@nestia/e2e";
import { createHash } from "node:crypto";
import { namedFacts, throwsError } from "../internal/predicates";
/** Recompute the identity digest without the engine primitive under test. */
const oracle: (value: unknown) => string = (value: unknown): string =>
  `sha256:${createHash("sha256")
    .update(Buffer.from(canonicalizeAutoMovieJson(value), "utf8"))
    .digest("hex")}`;

/** One chunk identity shaped exactly as the planner builds it. */
const identity: (overrides?: Record<string, unknown>) => Record<string, unknown> = (
  overrides: Record<string, unknown> = {},
): Record<string, unknown> => ({
  protocol: "automovie.production-render-chunk.v4",
  production: "demo-production",
  tier: { kind: "final", resolutionScale: 1, frameStep: 1 },
  deliverable: "feature",
  kind: "feature",
  editFingerprint: `sha256:${"a".repeat(64)}`,
  effects: [`sha256:${"b".repeat(64)}`],
  sourceFrameFormat: {
    width: 1920,
    height: 1080,
    frameRate: { numerator: 24, denominator: 1 },
  },
  frameFormat: {
    width: 1920,
    height: 1080,
    frameRate: { numerator: 24, denominator: 1 },
  },
  frameStart: 0,
  frameEndExclusive: 48,
  pass: "beauty",
  runtimeIdentity: {
    protocolVersion: "automovie.production-render-runtime.v3",
    sourceDigest: `sha256:${"c".repeat(64)}`,
    dialogueRuntimeIdentity: null,
    capture: {
      browser: "chromium",
      version: "140.0.0",
      backend: "swiftshader",
    },
    encoder: {
      package: "h264-mp4-encoder",
      version: "1.0.12",
      closureDigest: `sha256:${"d".repeat(64)}`,
      codec: "h264",
      arguments: { quantizationParameter: 20, speed: 4, groupOfPictures: 24 },
    },
  },
  sources: [{ shot: "shot-1", digest: `sha256:${"e".repeat(64)}` }],
  ...overrides,
});

/**
 * The chunk id keeps its bytes after moving to the engine digest primitive.
 *
 * Production computed a chunk id as SHA-256 over `Buffer.from(canonicalizeAutoMovieJson(identity), "utf8")`. The planner now lives in render and computes it as `autoMovieRenderDigest` of the same canonical text, which hashes that text's UTF-8 bytes through its own encoder and its own SHA-256. Plans and receipts already on disk carry ids from the old path, so the two must agree byte for byte or every stored plan reads as stale.
 *
 * Node crypto hashes the canonical text independently of the Engine byte encoder and hash. Both routes share the canonicalizer, which refuses lone surrogates before encoding; that case checks refusal rather than encoder parity.
 *
 * Scenarios:
 *
 * 1. A complete chunk identity digests identically through both paths.
 * 2. Identity is sensitive to the fields that decide a chunk: a different frame range, pass, tier or source digest each yields a different id, and none collides with another.
 * 3. Key insertion order does not change the id, because the canonicalizer orders properties before either encoder sees them.
 * 4. A lone surrogate anywhere in the identity is refused by the canonicalizer, so no digest is produced on either path.
 *
 * @evidence contracts/testing.md#behavioral-verification Compares Engine UTF-8/SHA chunk identities against Node crypto, checking changed frame range, pass, tier and source fields, property order and invalid Unicode refusal.
 * @evidence contracts/testing.md#independent-expectations Node Buffer and SHA-256 are independent of Engine byte encoding and hashing, but both routes intentionally share canonicalizeAutoMovieJson; this proves digest parity, not independently correct canonical JSON. The complete identity is authored rather than generated by the production planner.
 * @evidence contracts/testing.md#distinguishing-cases The full identity and four deciding-field variants, a reordered root and a lone surrogate cover parity, sensitivity and refusal; stored-plan admission and actual render-job planning have separate owning tests.
 * @evidence contracts/testing.md#execution-ownership The exported test_render_plan_chunk_digest_parity owns its cases. Portable canonical text and hash computation over an authored identity, with no production, encoder or browser launch.
 */
export function test_render_plan_chunk_digest_parity(): void {
  const engineDigest: (value: unknown) => string = (value: unknown): string =>
    autoMovieRenderDigest(canonicalizeAutoMovieJson(value));

  const complete: Record<string, unknown> = identity();
  TestValidator.equals(
    "a complete chunk identity agrees",
    engineDigest(complete),
    oracle(complete),
  );

  const variants: { range: Record<string, unknown>; pass: Record<string, unknown>; tier: Record<string, unknown>; source: Record<string, unknown>; } = {
    range: identity({ frameStart: 48, frameEndExclusive: 96 }),
    pass: identity({ kind: "guide-pass", pass: "pose" }),
    tier: identity({
      tier: { kind: "proxy", resolutionScale: 0.5, frameStep: 1 },
    }),
    source: identity({
      sources: [{ shot: "shot-1", digest: `sha256:${"f".repeat(64)}` }],
    }),
  };
  for (const [name, value] of Object.entries(variants))
    TestValidator.equals(
      `the ${name} variant agrees`,
      engineDigest(value),
      oracle(value),
    );

  const ids: string[] = [complete, ...Object.values(variants)].map(engineDigest);
  TestValidator.predicate(
    "every deciding field changes the id",
    (): boolean => new Set(ids).size === ids.length,
  );

  // The canonicalizer orders properties, so the same identity written in another
  // order is the same bytes and therefore the same id.
  const reordered: { sources: { digest: string; shot: string; }[]; protocol: string; } = {
    sources: [{ digest: `sha256:${"e".repeat(64)}`, shot: "shot-1" }],
    protocol: "automovie.production-render-chunk.v4",
    ...identity(),
  };
  TestValidator.equals(
    "property order does not change the id",
    engineDigest(reordered),
    engineDigest(complete),
  );

  const lone: Record<string, unknown> = identity({ deliverable: "feature\uD800" });
  TestValidator.equals(
    "a lone surrogate is refused, not digested",
    namedFacts([
      [
        "engineRefuses",
        (): boolean => throwsError((): string => engineDigest(lone), "invalid-unicode"),
      ],
      [
        "oracleRefuses",
        (): boolean => throwsError((): string => oracle(lone), "invalid-unicode"),
      ],
    ]),
    { engineRefuses: true, oracleRefuses: true },
  );
}
