import type {
  IAutoMovieAssetProvenance,
  IAutoMovieDiagnostic,
  IAutoMovieGeneratedAcquisition,
} from "@automovie/interface";
import { TestValidator } from "@nestia/e2e";
import { createHash } from "node:crypto";

import { productionAssetInventory } from "../../../../packages/production/src/production/productionAssetInventory";
import type { IAutoMovieProductionDesignGraph } from "../../../../packages/production/src/production/validateProductionDesign";

/**
 * Asset admission validates generation facts instead of accepting their shape.
 *
 * Scenarios:
 * 1. Local assets and consistent generated bytes are admitted.
 * 2. A blank provider, absent replay seed, wrong output, or wrong prompt fails.
 * 3. An irreproducible recorded seed remains advisory.
 * 4. Processing permits a changed current digest, while malformed generation
 *    facts still fail and an empty processing list permits no change.
 * 5. A supplementary Unicode instruction retains its exact UTF-8 identity;
 *    an unpaired surrogate cannot claim the replacement character's digest.
 *
 * @evidence contracts/testing.md#behavioral-verification Calls the production asset inventory with a serialized ledger and physical content; its diagnostic categories catch the previously unchecked generated record while allowing local and consistent generated assets.
 * @evidence contracts/testing.md#independent-expectations ASCII abc uses the standard SHA-256 digest; Unicode expectations hash literal UTF-8 byte sequences through Node crypto independently of the production hasher. Exact Unicode instructions cannot be replaced while retaining their claimed identity, and transformations change current bytes without changing origin.
 * @evidence contracts/testing.md#distinguishing-cases Separates absent and private prompt metadata, valid supplementary Unicode, unpaired surrogates, invalid fields, advisory seeds, transformed output, empty transformations and invalid transformed provenance. Engine tests own remaining numeric and digest boundaries.
 * @evidence contracts/testing.md#execution-ownership The exported unit entry exercises portable inventory semantics over caller-owned memory with direct source imports; no process, consumer installation, native artifact, or dynamic case registration is involved.
 */
export function test_production_generated_acquisition(): void {
  const digest: string =
    "sha256:ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad";
  const graph: IAutoMovieProductionDesignGraph = {
    production: null,
    models: new Map(),
    world: null,
    formations: new Map(),
    shots: new Map(),
    acceptance: new Map(),
  };
  const generated: IAutoMovieGeneratedAcquisition = {
    provider: "generator",
    model: "model-v1",
    request: null,
    prompt: "abc",
    promptDigest: digest,
    inputs: [],
    outputDigest: digest,
    reproducible: true,
    seed: 0,
  };
  const base: IAutoMovieAssetProvenance = {
    path: "assets/cue.bin",
    digest,
    uses: [{
      production: "production",
      consumer: { kind: "audio-cue", id: "cue" },
      reason: "Fixed cue bytes",
    }],
  };
  function inspect(asset: IAutoMovieAssetProvenance): IAutoMovieDiagnostic[] { return productionAssetInventory(
    "automovie/assets.json",
    [{
      path: "automovie/assets.json",
      source: false,
      render: false,
      bytes: Buffer.from(JSON.stringify({ version: 1, assets: [asset] })),
    }, {
      path: base.path,
      source: false,
      render: true,
      bytes: Buffer.from("abc"),
    }],
    "production",
    graph,
    new Map(),
  ).diagnostics; }
  TestValidator.equals("local provenance", inspect(base), []);
  TestValidator.equals("generated provenance", inspect({ ...base, generated }), []);
  TestValidator.equals("private prompt identity", inspect({
    ...base, generated: { ...generated, prompt: null },
  }), []);
  TestValidator.equals("supplementary Unicode instruction", inspect({
    ...base,
    generated: {
      ...generated,
      prompt: "\uD83D\uDE00",
      promptDigest: `sha256:${createHash("sha256").update(Uint8Array.of(0xf0, 0x9f, 0x98, 0x80)).digest("hex")}`,
    },
  }), []);
  const malformed: IAutoMovieGeneratedAcquisition[] = [
    { ...generated, provider: " " },
    { ...generated, seed: null },
    { ...generated, outputDigest: `sha256:${"0".repeat(64)}` },
    { ...generated, promptDigest: `sha256:${"0".repeat(64)}` },
    {
      ...generated,
      prompt: "\uD800",
      promptDigest: `sha256:${createHash("sha256").update(Uint8Array.of(0xef, 0xbf, 0xbd)).digest("hex")}`,
    },
  ];
  malformed.forEach((record: IAutoMovieGeneratedAcquisition, index: number): void => {
    const diagnostics: IAutoMovieDiagnostic[] = inspect({ ...base, generated: record });
    TestValidator.predicate(`generation refusal ${index}`, diagnostics.some(
      (finding: IAutoMovieDiagnostic): boolean =>
        finding.code === "asset-provenance-incomplete" && finding.category === "error",
    ));
  });
  TestValidator.equals("irreproducible seed remains advisory", inspect({
    ...base,
    generated: { ...generated, reproducible: false, seed: 3 },
  }).map((finding: IAutoMovieDiagnostic): string => finding.category), ["warning"]);
  const transformed: IAutoMovieAssetProvenance = {
    ...base,
    generated: { ...generated, outputDigest: `sha256:${"0".repeat(64)}` },
    processing: [{ tool: "transform-v1", command: "resample", parameters: {} }],
  };
  TestValidator.equals("transformed output", inspect(transformed), []);
  TestValidator.predicate("empty processing does not replace bytes", inspect({
    ...transformed,
    processing: [],
  }).some((finding: IAutoMovieDiagnostic): boolean => finding.category === "error"));
  TestValidator.predicate("processing does not bypass generation validity", inspect({
    ...transformed,
    generated: { ...generated, model: "" },
  }).some((finding: IAutoMovieDiagnostic): boolean => finding.category === "error"));
}
