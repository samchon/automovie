import { textDigest } from "./textDigest";

/**
 * Frame the existing in-memory source identity.
 *
 * @evidence contracts/testing.md#behavioral-verification Prefixes the exact supplied source text with source and a NUL delimiter before delegating to textDigest; no other project observation enters this fixture identity.
 * @evidence contracts/testing.md#independent-expectations The literal source-role framing is the existing world contract, while production's complete field-projection protocol is exercised by separate snapshot/composition units.
 * @evidence contracts/testing.md#distinguishing-cases Unchanged source retains identity and edited source moves it even if logical revision or generated bytes remain unchanged; those other observations are separate snapshot fields.
 * @evidence contracts/testing.md#execution-ownership Only framed text and the returned digest are local/transferred values; this helper neither evaluates authored source nor retains a cache.
 */
export const fingerprintOf: (source: string) => string = (source: string): string =>
  textDigest(`source\0${source}`);
