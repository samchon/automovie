import type { IAutoMovieMaterial, IAutoMovieMaterialOverlay, IAutoMovieMesh, IAutoMovieModel, IAutoMovieModelPart, IAutoMovieTextureReference } from "@automovie/interface";

import { AutoMovieHuman } from "../../../../packages/human/src/AutoMovieHuman";
import { HumanPeople } from "../internal/HumanPeople";

/**
 * Every dressed skin part of a generated figure carries the vertex attributes
 * its material reads, one per vertex and finite: the whole figure drew
 * blank under the skin material while it drew under the normals shading, so
 * a part whose texture coordinates, colours, relief weights or normals are
 * short or not finite, or whose triangles index past its vertices, or a skin
 * overlay whose transform is not finite, is what this lists.
 *
 * Scenarios:
 * 1. The first person of `HumanPeople` (or every person `AUTOMOVIE_HUMAN_PEOPLE` lists) is generated by `AutoMovieHuman.generate`; every mesh part whose material starts with `human.skin` or `human.cavity` is read for its positions, normals, texture coordinates, colours and relief weights (count per vertex and finiteness) and its indices (inside the vertex count), and the skin material's overlays for finite transforms; every defect is listed by part and the test fails on any.
 *
 * @evidence contracts/testing.md#behavioral-verification Calls the public `AutoMovieHuman.generate` and reads the model's own parts and materials; it catches attribute arrays shorter or longer than the vertex count, NaN or infinite values in any attribute a skin material samples, indices past the vertex count and non-finite overlay transforms, each of which keeps the renderer from drawing the part.
 * @evidence contracts/testing.md#independent-expectations Expectations are the mesh contract's counts (three per vertex for positions, normals and colours, two for texture coordinates, one for relief weights) and finiteness, not anything the generator reports.
 * @evidence contracts/testing.md#distinguishing-cases Positive: a figure whose skin is drawable. Negative: each defect kind is named separately per part, with its count and first index, so one bad attribute is told from another.
 * @evidence contracts/testing.md#execution-ownership A discoverable synchronous CPU unit reached by `--include human_skin_attributes`; it generates in process and starts no host, browser or GPU.
 */
export function test_human_skin_attributes(): void {
  const listed: string | undefined = process.env[HumanPeople.SET_VARIABLE];
  const names: string[] = listed !== undefined && listed !== "" ? HumanPeople.names() : [HumanPeople.names()[0]!];
  const failures: string[] = [];
  for (const name of names) {
    const model: IAutoMovieModel = AutoMovieHuman.generate(HumanPeople.params(name)).model;
    let skin: number = 0;
    for (const part of model.parts) {
      if (part.geometry.type !== "mesh") continue;
      const material: string = part.material ?? "";
      if (!material.startsWith("human.skin") && !material.startsWith("human.cavity")) continue;
      skin++;
      failures.push(...defects(`${name} ${part.id}`, part, part.geometry.mesh));
    }
    if (skin === 0) failures.push(`${name}: no skin part`);
    for (const material of model.materials.filter((m: IAutoMovieMaterial): boolean => m.id.startsWith("human.skin")))
      (material.overlays ?? []).forEach((o: IAutoMovieMaterialOverlay, k: number): void => {
        const t: IAutoMovieTextureReference["transform"] = typeof o.baseColorTexture === "string" ? undefined : o.baseColorTexture.transform;
        if (t !== undefined && ![t.offset.x, t.offset.y, t.scale.x, t.scale.y, t.rotationDeg].every(Number.isFinite)) failures.push(`${name} ${material.id} overlay ${k}: transform ${JSON.stringify(t)}`);
      });
    console.log(`${name}: ${skin} skin parts read`);
  }
  if (failures.length !== 0) throw new Error(`${failures.length} defects:\n${failures.slice(0, 60).join("\n")}`);
}

/** One part's attribute defects. */
function defects(label: string, part: IAutoMovieModelPart, mesh: IAutoMovieMesh): string[] {
  const out: string[] = [];
  const count: number = mesh.positions.length / 3;
  const check = (what: string, values: readonly number[] | null | undefined, per: number): void => {
    if (values === null || values === undefined) {
      out.push(`${label}: no ${what}`);
      return;
    }
    if (values.length !== per * count) out.push(`${label}: ${what} ${values.length} for ${count} vertices (want ${per * count})`);
    let bad: number = 0;
    let first: number = -1;
    values.forEach((v: number, i: number): void => {
      if (Number.isFinite(v)) return;
      bad++;
      if (first < 0) first = i;
    });
    if (bad > 0) out.push(`${label}: ${bad} non-finite ${what}, first at ${first} (${values[first]})`);
  };
  check("positions", mesh.positions, 3);
  check("normals", mesh.normals, 3);
  check("uvs", mesh.uvs, 2);
  check("colors", mesh.colors, 3);
  check("reliefWeights", mesh.reliefWeights, 1);
  const indices: readonly number[] = mesh.indices ?? [];
  const past: number = indices.filter((i: number): boolean => !(i >= 0 && i < count)).length;
  if (past > 0) out.push(`${label}: ${past} indices outside ${count} vertices`);
  if (indices.length % 3 !== 0) out.push(`${label}: ${indices.length} indices, not whole triangles`);
  void part;
  return out;
}
