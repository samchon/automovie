/** One source pinna's independent chart differences, zero at its native neutral.
 * Projection is lateral; recession deepens the named support. Fold witnesses
 * are authored source conventions, not acquired clinical cartilage boundaries.
 * @author Samchon
 */
export interface IHumanHeadEarSectionRecipe {
  /** Helix profile projection in millimetres. */
  helixRimProjectionOffsetMillimetres: number;

  /** Antihelix stem projection in millimetres. */
  antihelixProjectionOffsetMillimetres: number;

  /** Superior fork projection in millimetres. */
  superiorCrusProjectionOffsetMillimetres: number;

  /** Inferior fork projection in millimetres. */
  inferiorCrusProjectionOffsetMillimetres: number;

  /** Authored upper conchal support recession in millimetres. */
  cymbaFloorRecessionOffsetMillimetres: number;

  /** Authored lower conchal support recession in millimetres. */
  cavumFloorRecessionOffsetMillimetres: number;

  /** Tragus support projection in millimetres. */
  tragusProjectionOffsetMillimetres: number;

  /** Antitragus support projection in millimetres. */
  antitragusProjectionOffsetMillimetres: number;

  /** Inferior source lobule advancement in millimetres. */
  lobuleHeightOffsetMillimetres: number;

  /** Anterior/posterior lobule breadth difference in millimetres. */
  lobuleBreadthOffsetMillimetres: number;

  /** Paired surface-normal section separation difference in millimetres. */
  pinnaSectionThicknessOffsetMillimetres: number;

  /** Shared scalp/root recession in millimetres. */
  retroauricularSulcusRecessionOffsetMillimetres: number;

  /** Root-supported pinna inclination about native X, in degrees. */
  pinnaInclinationOffsetDegrees: number;
}
