

/**
 * Explicit source compilation paths and existing authoring budgets.
 * No attachment-specific defaults replace the normal appearance resolver.
 *
 * @author Samchon
 */
export interface IHumanSourceGenerationOptions {
  /** Verified acquisition and sampled work directory. */
  work: string;

  /** New publication directory; existing output refuses. */
  output: string;

  /** Checkout owning the pinned published inputs and producer. */
  repository: string;

  /** Optional authored root provider, paired with replay. */
  provider?: string;

  /** Complete same-sample endpoint replay for the provider. */
  replay?: string;

  /** Optional same-root authored head trait witnesses. */
  traitsDirectory?: string;

  /** Explicit unchanged shared occlusion authoring work budget. */
  oralEvaluations?: number;

  /** Explicit tongue budget, requiring occlusion authoring. */
  tongueEvaluations?: number;

  /** Completed-eye checkpoint retaining its full source refusal. */
  inspectionCheckpoint?: string;
}
