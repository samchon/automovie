import { retargetHumanoidMotion } from "@automovie/engine";
import type { IProductionExternalMotionAdoption } from "./IProductionExternalMotionAdoption";
import type { IProductionExternalMotionConversionDraft } from "./IProductionExternalMotionConversionDraft";
import { AutoMovieHumanoidBone, IAutoMovieActionCall, IAutoMovieModel, IAutoMovieShotActorProgram, IAutoMovieDiagnostic, IAutoMovieConstraintViolation, IAutoMovieExternalMotionLossEntry, IAutoMovieExternalMotionReceiptCharacterization, IAutoMovieMotion, IAutoMovieProductionShotProgram, IAutoMovieShotBuildContext, IAutoMovieSkeleton } from "@automovie/interface";
import { createAutoMovieSourceRuntimeModelRegistry } from "./createAutoMovieSourceRuntimeModelRegistry";
import { productionExternalMotionConversionDraft as externalMotionConversionDraft } from "./productionExternalMotionConversionDraft";
import { productionExternalMotionNativeRigCompatible as nativeExternalMotionRigCompatible } from "./productionExternalMotionNativeRigCompatible";

/**
 * Resolve each admitted adoption to the exact actor and selected enact actions.
 *
 * Native playback requires exact mapped rig compatibility. Retargeting delegates source/target admission and motion calculation to the engine. Usable contact warnings remain visible and compatible, with no invented semantic-loss authorization; errors produce no executable clip or conversion draft.
 *
 * @evidence contracts/common.md#principled-implementation Source clip collisions, missing articulated actors, unused adoptions and foreign/mixed actor consumers are refused before conversion; native mapped hierarchy/rest/constraint equality is exact, while the engine owns rig/motion admission, deterministic retarget calculation and typed findings; this bridge makes no clinical or visual-quality claim.
 * @evidence contracts/common.md#clear-and-simple-design Shot assembly consumes this one adoption resolver, inventory owns prior byte admission, and local receipt construction retains the declared source/target bases before generated materialization seals output identities.
 * @evidence contracts/common.md#prohibited-implementation-shortcuts No actor, take or mapping is inferred; final actions replace draft actions, native incompatibility never silently retargets, and usable physics advice does not become an unimplemented loss-approval requirement.
 * @evidence contracts/common.md#meaningful-documentation States actor/enact ownership, native-versus-retarget admission, warning compatibility and error refusal.
 * @evidence contracts/performance.md#efficient-algorithms Registry and authored-clip indexing visit M models and C clips once. For A adoptions, actor/action scans cost O(A(P+K)) for P actors and K selected actions, plus fallback model resolution and each native mapped-ancestor walk or engine retarget. Receipt work sorts mappings and hashes/clones source basis, target rig and motion; these complete bases are needed for sealed provenance.
 * @evidence contracts/performance.md#reuse-equivalent-work The shot shares one model registry and authored-clip set across its adoptions; retarget results are not cached across changed actors, rigs, mapping or scale, and each draft keeps its own provenance snapshot.
 * @evidence contracts/performance.md#bound-retention-and-release-resources Local indexes last for this shot resolution; accepted clips, diagnostics and deep-copied conversion drafts transfer to the build attempt and scale with adoption/motion populations without a fixed byte cap. No file, native process or asynchronous task is acquired.
 */
export function resolveExternalMotionClips(props: {
  /** Inventory-admitted external motions selected for this shot. */
  adoptions: readonly IProductionExternalMotionAdoption[];

  /** Synchronous authored program whose final-or-draft enact actions choose consumers. */
  program: IAutoMovieProductionShotProgram;

  /** Resolved builder/source models used to locate the declared actor's rig. */
  runtimeModels: IAutoMovieShotBuildContext["runtimeModels"];

  /** Shot identity used by conversion diagnostics. */
  target: string;

  /** Selected source module address used by conversion diagnostics. */
  sourcePath: string;
}): {
  /** Executable accepted clips; native motion references remain borrowed. */
  clips: IAutoMovieMotion[];

  /** Copied conversion drafts awaiting generated byte/result sealing. */
  conversions: IProductionExternalMotionConversionDraft[];

  /** Blocking conversion errors and advisory usable-motion warnings. */
  diagnostics: IAutoMovieDiagnostic[];
} {
  const clips: IAutoMovieMotion[] = [];
  const conversions: IProductionExternalMotionConversionDraft[] = [];
  const diagnostics: IAutoMovieDiagnostic[] = [];
  const modelRegistry: ReturnType<typeof createAutoMovieSourceRuntimeModelRegistry> = createAutoMovieSourceRuntimeModelRegistry(
    props.runtimeModels,
  );
  const authoredClipIds: Set<string> = new Set(
    (props.program.clips ?? []).map((clip: IAutoMovieMotion): string => clip.id),
  );
  for (const adoption of props.adoptions) {
    const declaration: IProductionExternalMotionAdoption["declaration"] = adoption.declaration;
    if (authoredClipIds.has(declaration.clip)) {
      diagnostics.push({
        code: "source-motion-adoption-invalid",
        category: "error",
        phase: "source",
        target: props.target,
        path: props.sourcePath,
        message: `External motion adoption "${declaration.id}" targets clip id "${declaration.clip}", but the shot source already declares that clip. Choose a distinct adoption clip id instead of replacing source-authored motion by map insertion order.`,
      });
      continue;
    }
    const actor: IAutoMovieShotActorProgram | undefined = props.program.actors.find(
      (candidate: IAutoMovieShotActorProgram): boolean => candidate.node === declaration.actor,
    );
    const targetModel: IAutoMovieModel | undefined =
      actor === undefined ? undefined : modelRegistry.resolve(actor.model);
    const targetSkeleton: IAutoMovieSkeleton | null = targetModel?.skeleton ?? null;
    if (actor === undefined || targetSkeleton === null) {
      diagnostics.push({
        code: "source-motion-adoption-invalid",
        category: "error",
        phase: "source",
        target: props.target,
        path: props.sourcePath,
        message: `External motion adoption "${declaration.id}" targets actor "${declaration.actor}", but that actor is absent or has no resolved articulated runtime model in this shot. Correct the explicit actor or model binding.`,
      });
      continue;
    }
    const actions: IAutoMovieActionCall[] =
      props.program.performance.revise.final ?? props.program.performance.draft;
    const consumers: Extract<IAutoMovieActionCall, { verb: "enact" }>[] = actions.filter(
      (action: IAutoMovieActionCall): action is Extract<IAutoMovieActionCall, { verb: "enact" }> => action.verb === "enact" && action.clip === declaration.clip,
    );
    if (consumers.length === 0) {
      diagnostics.push({
        code: "source-motion-adoption-invalid",
        category: "error",
        phase: "source",
        target: props.target,
        path: props.sourcePath,
        message: `External motion adoption "${declaration.id}" exposes clip "${declaration.clip}" for actor "${declaration.actor}", but the final performance never enacts it. Remove the unused adoption or enact that exact clip with the declared actor.`,
      });
      continue;
    }
    const wrongConsumer: Extract<IAutoMovieActionCall, { verb: "enact" }> | undefined = consumers.find((action: Extract<IAutoMovieActionCall, { verb: "enact" }>): boolean => {
      const actors: string[] = Array.isArray(action.actor)
        ? action.actor
        : [action.actor];
      return actors.length !== 1 || actors[0] !== declaration.actor;
    });
    if (wrongConsumer !== undefined) {
      const actors: string[] = Array.isArray(wrongConsumer.actor)
        ? wrongConsumer.actor
        : [wrongConsumer.actor];
      diagnostics.push({
        code: "source-motion-adoption-invalid",
        category: "error",
        phase: "source",
        target: props.target,
        path: props.sourcePath,
        message: `External motion adoption "${declaration.id}" belongs only to actor "${declaration.actor}", but final enact clip "${declaration.clip}" names actor set [${actors.map((value: string): string => `"${value}"`).join(", ")}]. Use the declared actor alone; same-rig or mixed actors do not inherit this adoption.`,
      });
      continue;
    }
    if (adoption.receipt.handoff.mode === "native") {
      if (
        adoption.sourceMotion.skeleton !== targetSkeleton.id ||
        nativeExternalMotionRigCompatible(
          adoption.receipt.handoff.sourceRig,
          adoption.receipt.handoff.mapping.map((entry: IProductionExternalMotionAdoption["receipt"]["handoff"]["mapping"][number]): AutoMovieHumanoidBone => entry.bone),
          targetSkeleton,
        ) === false
      ) {
        diagnostics.push({
          code: "source-motion-adoption-invalid",
          category: "error",
          phase: "source",
          target: props.target,
          path: props.sourcePath,
          message: `Native external motion adoption "${declaration.id}" was authored for source rig "${adoption.sourceMotion.skeleton}" but actor "${declaration.actor}" does not resolve the same mapped hierarchy, rest transforms, constraints, and rig identity in "${targetSkeleton.id}". Choose retarget mode or bind a byte-compatible native rig.`,
        });
        continue;
      }
      clips.push(adoption.sourceMotion);
      conversions.push(
        externalMotionConversionDraft({
          adoption,
          shot: declaration.shot,
          targetModel: actor.model,
          targetSkeleton,
          motion: adoption.sourceMotion,
          characterization: { status: "compatible", findings: [] },
          losses: [],
        }),
      );
      continue;
    }
    const retargeted: ReturnType<typeof retargetHumanoidMotion> = retargetHumanoidMotion({
      motion: adoption.sourceMotion,
      source: adoption.receipt.handoff.sourceRig,
      target: targetSkeleton,
      rootScale: adoption.receipt.handoff.translationScale,
      id: declaration.clip,
    });
    const findings: IAutoMovieConstraintViolation[] =
      retargeted.validation.success === false
        ? retargeted.validation.violations
        : (retargeted.validation.warnings ?? []);
    diagnostics.push(
      ...findings.map(
        (finding: IAutoMovieConstraintViolation): IAutoMovieDiagnostic => ({
          code: "source-motion-retarget-invalid",
          category: finding.severity === "error" ? "error" : "warning",
          phase: "source",
          target: props.target,
          path: props.sourcePath,
          message: `External motion adoption "${declaration.id}" retarget ${finding.path}: ${finding.expected}. Correct the declared source rig, target actor, mapping, or translation scale.`,
        }),
      ),
    );
    if (retargeted.validation.success && retargeted.motion !== null) {
      clips.push(retargeted.motion);
      const characterization: IAutoMovieExternalMotionReceiptCharacterization =
        {
          status: "compatible",
          findings: findings.map(
            (finding: IAutoMovieConstraintViolation): string => `${finding.path}: ${finding.expected}`,
          ),
        };
      // Successful engine findings describe usable contact residuals. They
      // remain warnings, not an unimplemented semantic-loss authorization.
      const losses: IAutoMovieExternalMotionLossEntry[] = [];
      conversions.push(
        externalMotionConversionDraft({
          adoption,
          shot: declaration.shot,
          targetModel: actor.model,
          targetSkeleton,
          motion: retargeted.motion,
          characterization,
          losses,
        }),
      );
    }
  }
  return { clips, conversions, diagnostics };
}
