import type { IAutoMovieProductionEvidence } from "@automovie/evidence";
import path from "node:path";

import type { AutoMovieProductionProject } from "./AutoMovieProductionProject";
import type { IAutoMovieProductionSourceSnapshot } from "./IAutoMovieProductionSourceSnapshot";
import {
  canonicalAutoMovieJsonBytes,
  compareCodeUnits,
  digestAutoMovieBytes,
} from "./contentIdentity";
import { captureAutoMovieLibraryAuthoringSnapshot } from "./libraryAuthoringSnapshot";
import { libraryBuildInputFingerprint } from "./libraryBuildInputFingerprint";
import { normalizeSlash } from "./productionBuildDiagnostics";
import { currentAutoMovieProductionBuildInputFingerprintWithEvidence } from "./productionBuildIdentity";
import { readAutoMovieLibraryDerivedInputs } from "./readAutoMovieLibraryDerivedInputs";

/**
 * Read one fresh source snapshot without executing authored source.
 *
 * Nothing here runs a module. The input identity is recomputed from the bytes
 * the builder would hash: a timed production through the projection its own
 * publication guard compares, and a library through its resident authoring
 * snapshot, portable projection and derived closure, chosen by the same
 * declared kind the builder dispatches on. The screenplay index, the requested
 * documents and every entry under the builder-owned root are then read as they
 * stand, because a gate answer depends on them and no fingerprint field carries
 * them.
 *
 * The revision is read first and last. A write through the project between the
 * two leaves no consistent observation, so the answer is `null` rather than a
 * snapshot that mixes two states; so is an input identity that cannot be
 * derived completely. Generated-entry read failures record a null digest so the
 * ownership gate can judge unreadable output; other reads can throw their cause.
 * Equal revision endpoints do not detect an untracked changed-and-restored edit.
 *
 * @evidence contracts/common.md#principled-implementation Brackets the builder input identity and additional screenplay/document/generated observations with project revision reads, returning null for incomplete identity or a moved revision. Library identity uses its resident snapshot and derived closure; generated read failure is an unreadable-entry fact rather than an absence claim.
 * @evidence contracts/common.md#clear-and-simple-design Supplies fresh observations to source-status retention without running authored modules or widening the generated manifest protocol; owning project readers enforce namespace admission and the gate separately evaluates observed ownership failures.
 * @evidence contracts/common.md#prohibited-implementation-shortcuts Every listed generated entry participates, including unreadable links; no unchanged revision alone proves equivalence. The revision bracket cannot detect untracked edits restored before the final read, and a null digest does not classify the read's failure cause.
 * @evidence contracts/common.md#meaningful-documentation States timed/library identity, supplemental observations, sorted distinct requested documents, generated failure-to-null policy, other exception propagation and the endpoint race limit.
 * @evidence contracts/performance.md#efficient-algorithms Includes the full input-fingerprint work and generated walk, hashes observed source/document/generated bytes, canonicalizes screenplay and manifest, and sorts D distinct document paths and F listed generated paths in O(D log D + F log F). Result storage grows with D+F paths and digests rather than retaining file buffers.
 * @evidence contracts/performance.md#reuse-equivalent-work Deduplicates requested document paths before reading and hashes each listed generated entry once; retention compares this fresh snapshot rather than relying on a watcher or prior revision. Filesystem observations are not cached across acquisitions.
 * @evidence contracts/performance.md#bound-retention-and-release-resources Local buffers and projections last through synchronous hashing, and the caller receives the snapshot. The finite listed/document populations determine its size with no fixed byte cap; project readers and the supplied walk own their handles.
 */
export function acquireAutoMovieProductionSourceSnapshot(props: {
  /** Project handle every read goes through. */
  project: AutoMovieProductionProject;

  /** Authoring evidence a current compile would be judged against. */
  authoring: IAutoMovieProductionEvidence | undefined;

  /** Author-owned documents to read, in any order and with repeats. */
  documents: readonly string[];

  /** Physical listing of one directory, the builder's own generated walk. */
  listFiles: (root: string) => string[];
}): IAutoMovieProductionSourceSnapshot | null {
  const project: AutoMovieProductionProject = props.project;
  const revision: number = project.revision();
  let inputFingerprint: string | null;
  let resident: string | null = null;
  if (props.authoring?.manifest.kind === "library") {
    const snapshot: ReturnType<typeof captureAutoMovieLibraryAuthoringSnapshot> = captureAutoMovieLibraryAuthoringSnapshot({
      root: project.root,
      evidence: props.authoring,
      readSource: (source: string): Uint8Array => project.readSource(source),
    });
    resident = snapshot.digest;
    inputFingerprint = libraryBuildInputFingerprint({
      production: project.productionId,
      snapshot,
      derivedFields: readAutoMovieLibraryDerivedInputs({
        project,
        enabled: true,
      }).fields,
    });
  } else
    inputFingerprint =
      currentAutoMovieProductionBuildInputFingerprintWithEvidence(
        project,
        "source",
        props.authoring,
      );
  if (inputFingerprint === null) return null;
  const screenplay: ReturnType<AutoMovieProductionProject["screenplayIndex"]> = project.screenplayIndex();
  const documents: IAutoMovieProductionSourceSnapshot["documents"] = [...new Set(props.documents)]
    .sort(compareCodeUnits)
    .map((document: string): IAutoMovieProductionSourceSnapshot["documents"][number] => {
      const text: string | null = project.readProseDocument(document);
      return {
        path: document,
        digest:
          text === null
            ? null
            : digestAutoMovieBytes(Buffer.from(text, "utf8")),
      };
    });
  const manifest: ReturnType<AutoMovieProductionProject["generatedManifest"]> = project.generatedManifest();
  const generatedRoot: string = project.generatedRoot();
  const files: IAutoMovieProductionSourceSnapshot["generated"]["files"] = props
    .listFiles(generatedRoot)
    .map((file: string): string => normalizeSlash(path.relative(generatedRoot, file)))
    .sort(compareCodeUnits)
    .map((file: string): IAutoMovieProductionSourceSnapshot["generated"]["files"][number] => {
      let digest: string | null;
      try {
        digest = digestAutoMovieBytes(project.readGeneratedFile(file));
      } catch {
        digest = null;
      }
      return { path: file, digest };
    });
  if (project.revision() !== revision) return null;
  return {
    revision,
    inputFingerprint,
    resident,
    screenplay:
      screenplay === null
        ? null
        : digestAutoMovieBytes(canonicalAutoMovieJsonBytes(screenplay)),
    documents,
    generated: {
      inputFingerprint: manifest?.inputFingerprint ?? null,
      manifest:
        manifest === null
          ? null
          : digestAutoMovieBytes(canonicalAutoMovieJsonBytes(manifest)),
      files,
    },
  };
}
