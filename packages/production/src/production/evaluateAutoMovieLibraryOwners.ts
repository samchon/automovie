import type { IAutoMovieProductionEvidence } from "@automovie/evidence";
import type {
  IAutoMovieDiagnostic,
  IAutoMovieLibraryBuildContext,
  IAutoMovieModel,
} from "@automovie/interface";

import { admitAutoMovieLibraryContribution } from "./admitAutoMovieLibraryContribution";
import { admitAutoMovieLibrarySettingsContribution } from "./admitAutoMovieLibrarySettingsContribution";
import {
  digestAutoMovieBytes,
  normalizeAutoMovieSource,
} from "./contentIdentity";
import type { IAutoMovieMaterializedLibraryResult } from "./materializeProduction";
import { errorMessage } from "./productionBuildDiagnostics";
import type { buildLibrarySource } from "./buildLibrarySource";
import { resolveAutoMovieSourceOwnerBinding } from "./resolveAutoMovieSourceOwnerBinding";

/**
 * Evaluate the acquired library source population and admit its contributions.
 *
 * The builder supplies the project reader, ordinary Node evaluator and engine
 * validators. This stage owns one attempt's registration and artifact identity
 * maps. It reads and normalizes each selected module before execution, binds
 * admission to the observed source digest and owner contexts, then preserves the first
 * registration at each address. A refused contribution still owns its claimed
 * identities so a later module cannot erase the failure by replacing it.
 *
 * Unreadable source becomes an attributed diagnostic and processing continues.
 * The evaluator has already shape-checked and admitted each returned owner;
 * therefore every registration resolves in the supplied context population.
 * Accepted results retain the source digest and contribution used by the later
 * publication stage. No generated bytes or persistent project state are written.
 * Node evaluates the current file through the supplied host rather than these
 * normalized text bytes; the coordinator's current-input confirmation must
 * still hold before publication, and arbitrary Node effects are not sandboxed.
 *
 * @evidence contracts/common.md#principled-implementation Ordered acquired source paths are freshly read and normalized for digest/owner admission; each valid registration claims its exact address before domain contribution admission, so a refusal cannot be overwritten by a later source under the same identity.
 * @evidence contracts/common.md#clear-and-simple-design This attempt owner shares registration and artifact-identity maps across admitted source modules; the evaluator owns ordinary Node loading/registration shape, branch admission owns contribution semantics and the coordinator owns final input confirmation/publication.
 * @evidence contracts/common.md#prohibited-implementation-shortcuts Missing source reports its own path, duplicate registrations preserve the first claim, settings deliveries are not treated as geometry and failed domain data cannot publish. Observed text digests do not prove the host executed that same buffer or had deterministic external effects.
 * @evidence contracts/common.md#meaningful-documentation States acquired-source ordering, observed-byte admission, evaluator's validated-context premise, identity reservation on refusal and nonpublishing/ordinary-Node limits.
 * @evidence contracts/performance.md#efficient-algorithms Cost includes full source reading/UTF-8 normalization/hashing, arbitrary Node evaluation and each domain validator; exact-address/artifact maps allow direct duplicate joins and scale with registrations and artifact ids. Each selected source is read once by this stage, while Node loading and later currentness scans remain separate costs.
 * @evidence contracts/performance.md#reuse-equivalent-work One attempt shares admitted owner contexts, source branches and registration/artifact maps; normalized source text supplies its digest and evaluation input record, but evaluated outputs are not cached across changed modules, contexts or derivation facts.
 * @evidence contracts/performance.md#bound-retention-and-release-resources Results and diagnostics transfer to the library attempt, with retained contribution/model/index bytes growing with authored population without a fixed cap; local source text is released per iteration, readers own filesystem handles and authored Node code owns any effects it creates.
 */
export function evaluateAutoMovieLibraryOwners(props: {
  /** Project root whose ordinary evaluator loads the selected modules. */
  root: string;

  /** Canonically ordered source paths from the acquired authoring snapshot. */
  sources: readonly string[];

  /** Exact source-owner edges from that same snapshot. */
  bindings: IAutoMovieProductionEvidence["sourceOwners"];

  /** Validated owner addresses available during evaluation. */
  contexts: ReadonlyMap<string, IAutoMovieLibraryBuildContext>;

  /** Source binding branch selected for each context address. */
  sourceBranches: ReadonlyMap<string, string>;

  /** Completion gate choice used for source-edge admission. */
  requireReviewed: boolean;

  /** Reader from the same project handle that guards publication. */
  readSource: (source: string) => Uint8Array;

  /** Host evaluator that returns only shape-checked, admitted registrations. */
  evaluate: typeof buildLibrarySource;

  /** Domain validators shared with the builder's native compilation path. */
  validators: Parameters<
    typeof admitAutoMovieLibraryContribution
  >[0]["validators"];
}): {
  results: IAutoMovieMaterializedLibraryResult[];
  registeredBy: ReadonlyMap<string, string>;
  diagnostics: IAutoMovieDiagnostic[];
} {
  const results: IAutoMovieMaterializedLibraryResult[] = [];
  const registeredBy: Map<string, string> = new Map<string, string>();
  const diagnostics: IAutoMovieDiagnostic[] = [];
  const environmentOwner: Map<string, string> = new Map<string, string>();
  const contextOwner: Map<string, string> = new Map<string, string>();
  const models: Map<string, IAutoMovieModel> = new Map<string, IAutoMovieModel>();
  const modelOwner: Map<string, string> = new Map<string, string>();
  for (const source of props.sources) {
    let text: string;
    try {
      text = Buffer.from(
        normalizeAutoMovieSource(props.readSource(source)),
      ).toString("utf8");
    } catch (error) {
      diagnostics.push({
        code: "source-path-missing",
        category: "error",
        phase: "source",
        target: `library-source:${source}`,
        path: source,
        message: `Library source "${source}" is selected by a reviewed source binding but cannot be read (${errorMessage(error)}). Restore the exact tracked file or correct the binding before compiling.`,
      });
      continue;
    }
    const sourceDigest: string = digestAutoMovieBytes(Buffer.from(text, "utf8"));
    const compiled: ReturnType<typeof props.evaluate> = props.evaluate({
      path: source,
      source: text,
      sourceRoot: props.root,
      context: (design: string): IAutoMovieLibraryBuildContext | null => props.contexts.get(design) ?? null,
      admit: (exportName: string, design: string): ReturnType<typeof resolveAutoMovieSourceOwnerBinding> =>
        resolveAutoMovieSourceOwnerBinding({
          bindings: props.bindings,
          branch: props.sourceBranches.get(design)!,
          sourcePath: source,
          exportName,
          owner: design,
          sourceDigest,
          requireReviewed: props.requireReviewed,
        }),
    });
    diagnostics.push(...compiled.diagnostics);
    for (const registration of compiled.registrations) {
      const context: IAutoMovieLibraryBuildContext = props.contexts.get(registration.design)!;
      const target: string = `library:${context.branch}:${registration.design}`;
      const previous: string | undefined = registeredBy.get(registration.design);
      if (previous !== undefined) {
        diagnostics.push({
          code: "source-registration-mismatch",
          category: "error",
          phase: "source",
          target,
          path: source,
          message: `Library design owner "${registration.design}" is registered by both "${previous}" and "${source}#${registration.export}". Keep one source export per reviewed H2; two registrations make the published artifact depend on file order.`,
        });
        continue;
      }
      registeredBy.set(registration.design, `${source}#${registration.export}`);
      const accepted: boolean =
        context.branch === "productionSources"
          ? admitAutoMovieLibrarySettingsContribution({
              diagnostics,
              registration,
              source,
              target,
            })
          : admitAutoMovieLibraryContribution({
              diagnostics,
              contextOwner,
              environmentOwner,
              modelOwner,
              models,
              registration,
              source,
              target,
              validators: props.validators,
            });
      if (accepted === false) continue;
      results.push({
        branch: context.branch,
        owner: registration.design,
        source,
        export: registration.export,
        sourceDigest,
        contribution: registration.contribution,
      });
    }
  }
  return { results, registeredBy, diagnostics };
}
