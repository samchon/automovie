
import type { IProductionExternalMotionAdoption } from "./IProductionExternalMotionAdoption";
import type { IProductionExternalMotionConversionDraft } from "./IProductionExternalMotionConversionDraft";
import { AutoMovieHumanoidBone, IAutoMovieExternalMotionMappingEntry, IAutoMovieExternalMotionReceiptResource, IAutoMovieTrack, IAutoMovieExternalMotionLossEntry, IAutoMovieExternalMotionReceiptCharacterization, IAutoMovieExternalMotionTransformActivity, IAutoMovieMotion, IAutoMovieSkeleton } from "@automovie/interface";
import { canonicalAutoMovieJsonBytes, compareCodeUnits, digestAutoMovieBytes } from "./contentIdentity";
import { AUTOMOVIE_PRODUCTION_BUILD_PROTOCOL, AUTOMOVIE_PRODUCTION_BUILD_VERSION } from "./productionBuildProtocol";

/**
 * Assemble fixed conversion provenance before canonical generated output identities exist.
 *
 * Mappings are copied and sorted; source basis, target basis, channel transforms, loss entries, characterization and motion become this attempt's receipt draft. Output path/digest and canonical enacted motion identity are added later by materializeGeneratedFiles, not inferred here.
 *
 * @evidence contracts/common.md#principled-implementation Inventory-admitted take/basis/mapping and the resolver's accepted motion supply the draft. Canonical basis hashing and structured clones bind those observations, while channel target lookup assumes prior complete mapping and cannot independently authenticate source bytes.
 * @evidence contracts/common.md#clear-and-simple-design Semantic conversion metadata stays separate from generated byte sealing and physical publication; the original resolver remains the only caller of this internal helper.
 * @evidence contracts/common.md#prohibited-implementation-shortcuts Mode-specific retarget/translation-scale records follow the declared supported conversion mode. Missing mapping is not runtime-validated here, and characterization/loss inputs are preserved rather than manufactured approval receipts.
 * @evidence contracts/common.md#meaningful-documentation Documents prior mapping/byte admission, copied provenance, mode-specific transforms, accepted motion and missing generated result identity.
 * @evidence contracts/performance.md#efficient-algorithms Cost includes mapping sort O(K log K) string comparisons, track-to-channel projections, full basis/rig canonicalization and hashing, motion structured clone and copied loss/finding populations. Complete motion/keyframe and provenance bytes dominate retained storage.
 * @evidence contracts/performance.md#reuse-equivalent-work The bone-by-node map serves all channel targets in this draft; each adoption seals its own bases/motion and no retained retarget or provenance cache crosses changed inputs.
 * @evidence contracts/performance.md#bound-retention-and-release-resources The build attempt owns the returned copied draft through serialization/refusal, with no byte/keyframe cap here. Temporary lookup maps expire, and the helper opens no file, native artifact or running task.
 */
export function productionExternalMotionConversionDraft(props: {
  /** Inventory-admitted source bytes, selected take, basis and authored decision. */
  adoption: IProductionExternalMotionAdoption;

  /** Shot whose compiled output later seals the conversion result. */
  shot: string;

  /** Authored target model reference retained in provenance. */
  targetModel: string;

  /** Resolved target rig whose complete canonical basis is hashed. */
  targetSkeleton: IAutoMovieSkeleton;

  /** Accepted normalized motion, cloned into this pre-publication draft. */
  motion: IAutoMovieMotion;

  /** Resolver-selected compatibility and visible finding text. */
  characterization: IAutoMovieExternalMotionReceiptCharacterization;

  /** Explicit loss records preserved as data; current usable conversions provide none. */
  losses: IAutoMovieExternalMotionLossEntry[];
}): IProductionExternalMotionConversionDraft {
  const declaration: IProductionExternalMotionAdoption["declaration"] = props.adoption.declaration;
  const mapping: IAutoMovieExternalMotionMappingEntry[] = declaration.mapping
    .map((entry: IAutoMovieExternalMotionMappingEntry): IAutoMovieExternalMotionMappingEntry => ({ ...entry }))
    .sort(
      (left: IAutoMovieExternalMotionMappingEntry, right: IAutoMovieExternalMotionMappingEntry): number =>
        compareCodeUnits(left.source, right.source) ||
        compareCodeUnits(left.target, right.target),
    );
  const channelSources: string[] = props.adoption.receipt.take.tracks.map((track: IAutoMovieTrack): string =>
    track.channel.kind === "node"
      ? `${track.channel.node}:${track.channel.path}`
      : `${track.channel.pointer}:${track.channel.valueType}`,
  );
  const boneByNode: Map<string, AutoMovieHumanoidBone> = new Map(
    mapping.map((entry: IAutoMovieExternalMotionMappingEntry): [string, AutoMovieHumanoidBone] => [entry.source, entry.target]),
  );
  const channelTargets: string[] = props.adoption.receipt.take.tracks.map((track: IAutoMovieTrack): string =>
    track.channel.kind === "node"
      ? `${boneByNode.get(track.channel.node)!}:${track.channel.path}`
      : track.channel.pointer,
  );
  const transforms: IAutoMovieExternalMotionTransformActivity[] = [
    {
      kind: "channel-conversion",
      source: channelSources,
      target: channelTargets,
      parameters: {
        take: declaration.take,
        sourceTracks: channelSources.length,
        resultChannels: channelTargets.length,
      },
    },
  ];
  if (declaration.mode.kind === "humanoid-retarget") {
    transforms.push({
      kind: "retarget",
      source: mapping.map((entry: IAutoMovieExternalMotionMappingEntry): string => entry.source),
      target: mapping.map((entry: IAutoMovieExternalMotionMappingEntry): AutoMovieHumanoidBone => entry.target),
      parameters: {
        sourceRig: declaration.sourceRig.id,
        targetRig: props.targetSkeleton.id,
      },
    });
    transforms.push({
      kind: "translation-scale",
      source: ["hips:translation"],
      target: ["hips:translation"],
      parameters: { scale: declaration.mode.translationScale },
    });
  }
  return {
    version: 1,
    builder: {
      packageVersion: AUTOMOVIE_PRODUCTION_BUILD_VERSION,
      protocolVersion: AUTOMOVIE_PRODUCTION_BUILD_PROTOCOL,
    },
    adoption: declaration.id,
    source: {
      asset: {
        path: props.adoption.receipt.source.path,
        digest: props.adoption.receipt.source.digest,
      },
      closure: props.adoption.sourceClosure.map((entry: IAutoMovieExternalMotionReceiptResource): IAutoMovieExternalMotionReceiptResource => ({ ...entry })),
      take: { ...props.adoption.sourceTake },
      basis: structuredClone(props.adoption.sourceBasis),
      basisDigest: digestAutoMovieBytes(
        canonicalAutoMovieJsonBytes(props.adoption.sourceBasis),
      ),
    },
    decision: {
      shot: props.shot,
      actor: declaration.actor,
      clip: declaration.clip,
      mode: declaration.mode.kind,
      mapping,
      translationScale:
        declaration.mode.kind === "humanoid-retarget"
          ? declaration.mode.translationScale
          : null,
    },
    target: {
      model: props.targetModel,
      skeleton: props.targetSkeleton.id,
      basisDigest: digestAutoMovieBytes(
        canonicalAutoMovieJsonBytes(props.targetSkeleton),
      ),
    },
    transforms,
    losses: props.losses.map((entry: IAutoMovieExternalMotionLossEntry): IAutoMovieExternalMotionLossEntry => ({
      ...entry,
      source: [...entry.source],
    })),
    characterization: {
      status: props.characterization.status,
      findings: [...props.characterization.findings],
    },
    motion: structuredClone(props.motion),
  };
}
