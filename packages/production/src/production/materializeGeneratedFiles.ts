
import { IAutoMovieCompiledContractRealization, IAutoMovieCompiledFilmEdit, IAutoMovieCompiledFilmEffect, IAutoMovieCompiledShotSource, IAutoMovieExternalMotionConversionReceipt, IAutoMovieFilmTimeline } from "@automovie/interface";
import { AutoMovieProductionProject } from "./AutoMovieProductionProject";
import { canonicalAutoMovieJsonBytes, compareCodeUnits, digestAutoMovieBytes, encodeAutoMoviePathSegment } from "./contentIdentity";
import { AUTOMOVIE_PRODUCTION_BUILD_PROTOCOL } from "./productionBuildProtocol";
import type { IProductionExternalMotionConversionDraft } from "./IProductionExternalMotionConversionDraft";

/**
 * Serialize prepared timed-production records into detached generated candidate bytes.
 *
 * Contracts, runtime models and compiled shots keep their supplied map order; external-motion adoptions and registry id lists use code-unit order. Each conversion receipt identifies the compiled actor performance's canonical motion and exact serialized shot bytes, refusing a missing output or enacted motion. The returned map is staged data, not publication.
 *
 * @evidence contracts/common.md#principled-implementation Canonical JSON plus a trailing LF gives each record deterministic bytes within the engine's supported JSON domain. Timed orchestration can serialize partial records before final diagnostics refuse publication; this serializer does not independently admit the graph. Motion receipt sealing reads actual compiled output rather than trusting draft motion identity, and canonical-domain failures propagate.
 * @evidence contracts/common.md#clear-and-simple-design One serializer owns generated paths and ownership-registry contents; compilation owns admission and commitGenerated owns physical publication, rollback and revision accounting.
 * @evidence contracts/common.md#prohibited-implementation-shortcuts Encoded ids use the shared portable path owner. The serialization order and manifests/compile.json address are protocol choices; no fixture or absent conversion gets a substitute output. Map order remains an input premise rather than being described as order-independent.
 * @evidence contracts/common.md#meaningful-documentation States record order, detached bytes, canonical motion/output receipt binding, missing-result refusals and candidate-versus-published ownership.
 * @evidence contracts/performance.md#efficient-algorithms Cost includes canonical traversal/key sorting and encoding all contracts/models/shots/realizations/film data, sorting A adoptions and registry ids, scanning each selected shot's performances/motions and hashing full motion/shot bytes. The returned map retains all generated bytes, without a size cap here.
 * @evidence contracts/performance.md#reuse-equivalent-work Each shot is serialized once and those existing output bytes are reused for its receipt digest; repeated receipts can still rehash the same shot. No candidate cache crosses changed design, compiled motion or namespace inputs.
 * @evidence contracts/performance.md#bound-retention-and-release-resources The caller owns the returned map and detached buffers until publication or refusal. Supplied graph/compiled values remain borrowed, and temporary canonical text/buffers expire locally; this serializer opens no file or running task.
 */
export function materializeGeneratedFiles(
  productionId: string,
  graph: ReturnType<AutoMovieProductionProject["graph"]>,
  runtimeModels: ReadonlyMap<
    string,
    IAutoMovieCompiledShotSource["models"][number]
  >,
  compiled: ReadonlyMap<string, IAutoMovieCompiledShotSource>,
  externalMotionConversions: ReadonlyMap<
    string,
    IProductionExternalMotionConversionDraft
  >,
  realizations: ReadonlyMap<string, IAutoMovieCompiledContractRealization>,
  film: {
    edit: IAutoMovieCompiledFilmEdit;
    timeline: IAutoMovieFilmTimeline;
    effects: IAutoMovieCompiledFilmEffect[];
  } | null,
  inputFingerprint: string
): ReadonlyMap<string, Uint8Array> {
  const files: Map<string, Uint8Array> = new Map<string, Uint8Array>();
  const put: (file: string, value: unknown) => void = (file: string, value: unknown): void => {
    files.set(
      file,
      Buffer.concat([
        Buffer.from(canonicalAutoMovieJsonBytes(value)),
        Buffer.from("\n", "utf8"),
      ]),
    );
  };
  put("contracts/production.json", graph.production);
  put("contracts/world.json", graph.world);
  for (const [id, value] of graph.models)
    put(`contracts/models/${encodeAutoMoviePathSegment(id)}.json`, value);
  for (const [id, value] of graph.formations)
    put(`contracts/formations/${encodeAutoMoviePathSegment(id)}.json`, value);
  for (const [id, value] of graph.shots)
    put(`contracts/shots/${encodeAutoMoviePathSegment(id)}.json`, value);
  for (const [id, value] of graph.acceptance)
    put(`contracts/acceptance/${encodeAutoMoviePathSegment(id)}.json`, value);
  for (const [id, value] of runtimeModels)
    put(`models/${encodeAutoMoviePathSegment(id)}.json`, value);
  for (const [id, value] of compiled)
    put(`shots/${encodeAutoMoviePathSegment(id)}.json`, value);
  for (const [adoption, draft] of [...externalMotionConversions].sort(
    ([left]: [string, IProductionExternalMotionConversionDraft], [right]: [string, IProductionExternalMotionConversionDraft]): number => compareCodeUnits(left, right),
  )) {
    const outputPath: string = `shots/${encodeAutoMoviePathSegment(draft.decision.shot)}.json`;
    const outputBytes: Uint8Array | undefined = files.get(outputPath);
    if (outputBytes === undefined)
      throw new Error(
        `External motion conversion "${adoption}" has no materialized shot output "${outputPath}".`,
      );
    const { motion, ...receipt }: IProductionExternalMotionConversionDraft = draft;
    const compiledShot: IAutoMovieCompiledShotSource | undefined = compiled.get(draft.decision.shot);
    const resultMotionId: IAutoMovieCompiledShotSource["shot"]["performances"][number]["motion"] | undefined = compiledShot?.shot.performances.find(
      (performance: IAutoMovieCompiledShotSource["shot"]["performances"][number]): boolean => performance.node === draft.decision.actor,
    )?.motion;
    const resultMotion: IAutoMovieCompiledShotSource["motions"][number] | undefined = compiledShot?.motions.find(
      (candidate: IAutoMovieCompiledShotSource["motions"][number]): boolean => candidate.id === resultMotionId,
    );
    if (resultMotion === undefined)
      throw new Error(
        `External motion conversion "${adoption}" for actor "${draft.decision.actor}" has no canonical enacted performance in materialized shot "${draft.decision.shot}".`,
      );
    const value: IAutoMovieExternalMotionConversionReceipt = {
      ...receipt,
      result: {
        motionId: resultMotion.id,
        motionDigest: digestAutoMovieBytes(
          canonicalAutoMovieJsonBytes(resultMotion),
        ),
        outputPath,
        outputDigest: digestAutoMovieBytes(outputBytes),
      },
    };
    put(
      `receipts/external-motion/${encodeAutoMoviePathSegment(adoption)}.json`,
      value,
    );
  }
  for (const [id, value] of realizations)
    put(`realizations/${encodeAutoMoviePathSegment(id)}.json`, value);
  if (film !== null) {
    put("contracts/film-edit.json", film.edit);
    put("film-timeline.json", film.timeline);
    put("film-effects.json", film.effects);
  }
  put("manifests/compile.json", {
    version: 2,
    builder: AUTOMOVIE_PRODUCTION_BUILD_PROTOCOL,
    productionId,
    inputFingerprint,
    assets: [...runtimeModels.keys()].sort(compareCodeUnits).map((id: string): { id: string; path: string } => ({
      id,
      path: `models/${encodeAutoMoviePathSegment(id)}.json`,
    })),
    shots: [...compiled.keys()].sort(compareCodeUnits).map((id: string): { id: string; path: string } => ({
      id,
      path: `shots/${encodeAutoMoviePathSegment(id)}.json`,
    })),
    film: film?.timeline.id ?? null,
  });
  return files;
}
