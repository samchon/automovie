import type { IAutoMovieProductionEvidence } from "@automovie/evidence";
import type { IAutoMovieBuildProjectOutput } from "@automovie/interface";
import { createRequire } from "node:module";
import path from "node:path";

import type { AutoMovieProductionProject } from "./AutoMovieProductionProject";
import type { IAutoMovieProductionSourceEvaluation } from "./IAutoMovieProductionSourceEvaluation";
import type { IAutoMovieProductionSourceSnapshot } from "./IAutoMovieProductionSourceSnapshot";
import { acquireAutoMovieProductionSourceSnapshot } from "./acquireAutoMovieProductionSourceSnapshot";
import { evaluateAutoMovieProductionSource } from "./evaluateAutoMovieProductionSource";
import { listFiles } from "./productionBuildDiagnostics";
import { retainAutoMovieProductionSourceStatus } from "./retainAutoMovieProductionSourceStatus";

/**
 * Open the read-only source gate status one project's checks share.
 *
 * Capture, receipt reopen, guarded commits, inspection and repaint share a status answer for the same project handle and input identity. This composes fresh snapshot acquisition, the builder's read-only gate, a supplied generated walk and the process module cache; retention requires fresh matching observations and the gate's declared dependencies.
 *
 * Snapshot acquisition uses the live authoring reader when supplied, otherwise the fixed declaration. The builder carries its own evidence, so a caller that needs fresh compilation evidence must also supply a builder that reads it on every run.
 *
 * Runtime observations belong to the host that executed that builder. The default reads Node's live module cache and walks generated regular files and symbolic links without following links. A custom host must supply the generated population relevant to its ownership checks and a live cache object reflecting completed gate execution; a cache copy taken before the run cannot establish that closure. Neither the port nor the default observations prove atomic filesystem state or deterministic Node effects.
 *
 * @evidence contracts/common.md#principled-implementation Fresh snapshots bind content, authoring, prose, generated bytes and revision dependencies to one successful read-only evaluation; retention requires matching before/after observations, gate identity and a fully declared executed-module closure.
 * @evidence contracts/common.md#clear-and-simple-design The opened production exposes one shared status closure; acquisition, gate evaluation and equivalence retention have concrete owners, and the optional runtime port supplies complete host observations without changing admission.
 * @evidence contracts/common.md#prohibited-implementation-shortcuts Failed/incomplete observations cannot authorize cached success, failed gate answers are not retained, and loader observations must remain live through evaluation rather than hiding undeclared executed modules.
 * @evidence contracts/common.md#meaningful-documentation States shared callers, live/fixed authoring behavior, builder evidence premise and complete live loader/generated observations.
 * @evidence contracts/performance.md#efficient-algorithms Every status request rereads and hashes current declared input, prose and generated entries; an equivalent success avoids authored evaluation, while a new success may pay a second snapshot. Retention compares serialized snapshot bytes and clones output, so cost includes total snapshot/output size as well as domain gate work.
 * @evidence contracts/performance.md#reuse-equivalent-work One closure shares only a proved successful answer across the same project's consumers, invalidating it before every fresh observation. Dependencies include actual document reads, generated inventory, executed module declaration and revision when the gate used it; effectful compilation itself is never shared across concurrent attempts here.
 * @evidence contracts/performance.md#bound-retention-and-release-resources The returned closure retains project/builder/runtime references and at most one successful snapshot/output, whose bytes scale with admitted project populations without a fixed cap; replacement or caller disposal releases references, and project readers own filesystem handles.
 */
export function createAutoMovieProductionSourceStatus(props: {
  /** Project handle every snapshot and gate run reads. */
  project: AutoMovieProductionProject;

  /** Builder whose read-only source gate answers the status. */
  builder: Parameters<typeof evaluateAutoMovieProductionSource>[0]["builder"];

  /** Fixed graph-derived authoring identity, used when no live reader exists. */
  authoringEvidence?: IAutoMovieProductionEvidence;

  /** Fresh graph reader a current compile would consult. */
  currentAuthoringEvidence?: () => IAutoMovieProductionEvidence;

  /** Complete generated and loader observations of the same project runtime. */
  runtime?: {
    /** Physical generated-root listing, including unowned and linked entries. */
    listFiles: (root: string) => string[];

    /** Live cache object reflecting the loader's completed source-gate execution. */
    moduleCache: () => Readonly<Record<string, unknown>>;
  };
}): (() => IAutoMovieBuildProjectOutput) {
  const runtime: NonNullable<typeof props.runtime> = props.runtime ?? {
    listFiles,
    moduleCache: (): Readonly<Record<string, unknown>> =>
      createRequire(path.join(props.project.root, "package.json")).cache,
  };
  return retainAutoMovieProductionSourceStatus({
    acquire: (documents: readonly string[]): IAutoMovieProductionSourceSnapshot | null =>
      acquireAutoMovieProductionSourceSnapshot({
        project: props.project,
        authoring:
          props.currentAuthoringEvidence?.() ?? props.authoringEvidence,
        documents,
        listFiles: runtime.listFiles,
      }),
    evaluate: (): IAutoMovieProductionSourceEvaluation =>
      evaluateAutoMovieProductionSource({
        project: props.project,
        builder: props.builder,
        moduleCache: runtime.moduleCache(),
      }),
  });
}
