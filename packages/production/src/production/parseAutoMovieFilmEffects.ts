import { verifyProductionFilmEffectPopulation } from "@automovie/engine";
import { IAutoMovieCompiledFilmEffect, IAutoMovieFilmTimeline, IAutoMovieGeneratedManifest } from "@automovie/interface";
import typia from "typia";
import { digestAutoMovieBytes } from "./contentIdentity";
import { parseAutoMovieStructuredJson } from "./duplicateAwareJson";
import type { IAutoMovieFilmTimelineArtifact } from "./IAutoMovieFilmTimelineArtifact";

/**
 * Admit generated effects bytes and their exact executable population against the supplied timeline.
 *
 * @evidence contracts/common.md#principled-implementation Manifest fingerprint/entry, byte digest, strict JSON/schema and per-entry compile fingerprint checks precede the engine's ordered cue/runtime population comparison.
 * @evidence contracts/common.md#clear-and-simple-design Owns generated effect artifact admission while the engine owns reduced clock, edit/runtime identities and cue bijection; exported parser currently has no live application invocation.
 * @evidence contracts/common.md#prohibited-implementation-shortcuts Empty or truncated runtime populations cannot pass a nonempty track; the engine deliberately cannot compare production id because the timeline has no such field, and this parser does not invent it.
 * @evidence contracts/common.md#meaningful-documentation Defines generated byte/current compile checks and delegated population refusals; the supplied timeline must itself have been admitted by its caller.
 * @evidence contracts/performance.md#efficient-algorithms Scans F manifest entries and all B bytes/schema/effects; engine validation adds cue sorting O(C log C), serialized timeline edit hashing and per-runtime identity validation.
 * @evidence contracts/performance.md#reuse-equivalent-work One materialized effect tree supplies schema, fingerprint and population validation; engine rate/edit/sorted cues are computed once per validation call without a cross-call cache.
 * @evidence contracts/performance.md#bound-retention-and-release-resources Buffers/text/validation frames are attempt-local and complete effects transfer; engine cue copies coexist temporarily, with no native descriptor acquired here.
 */
export function parseAutoMovieFilmEffects(artifact: IAutoMovieFilmTimelineArtifact, timeline: IAutoMovieFilmTimeline): IAutoMovieCompiledFilmEffect[] {
    const entry: IAutoMovieGeneratedManifest['files'][number] | undefined = artifact.manifest?.files.find((file: IAutoMovieGeneratedManifest['files'][number]): boolean => file.path === "film-effects.json");
    if (artifact.manifest?.inputFingerprint !== artifact.fingerprint ||
        entry === undefined)
        throw new Error("Compiler-owned film effects are missing or changed after compilation. Run the scaffold source compile command.");
    const bytes: Uint8Array = artifact.read(entry.path);
    if (digestAutoMovieBytes(bytes) !== entry.digest)
        throw new Error("Compiler-owned film effect bytes differ from the generated manifest. Run the scaffold source compile command.");
    const validation: typia.IValidation<IAutoMovieCompiledFilmEffect[]> = typia.validateEquals<IAutoMovieCompiledFilmEffect[]>(parseAutoMovieStructuredJson({ record: "film-effects", bytes }));
    if (validation.success === false ||
        validation.data.some((effect: IAutoMovieCompiledFilmEffect): boolean => effect.compileFingerprint !== artifact.fingerprint))
        throw new Error("Compiler-owned film effects are invalid or stale. Run the scaffold source compile command.");
    verifyProductionFilmEffectPopulation({
        timeline,
        effects: validation.data,
    });
    return validation.data;
}
