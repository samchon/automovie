import { readProductionPublicationInputFingerprint } from "./readProductionPublicationInputFingerprint";
import type { IAutoMovieProductionEvidence } from "@automovie/evidence";
import { IAutoMovieBuildProjectOutput, type IAutoMovieGeneratedManifest, type IAutoMovieGeneratedFile } from "@automovie/interface";
import { AutoMovieProductionBuilder } from "./AutoMovieProductionBuilder";
import { AutoMovieProductionProject } from "./AutoMovieProductionProject";
import { digestAutoMovieBytes } from "./contentIdentity";

/**
 * Fingerprint currently observed inputs to terminal production publication.
 *
 * The snapshot includes revision, exact local incarnation bytes, cached manifest semantics and their JSON digest, design graph entries, generated ownership and freshly hashed generated member bytes. It does not hash raw project-manifest file bytes or acquire an atomic snapshot. The maintained tree exposes this utility through the production barrel and exercises it in a source-status unit; no current production publication calls it.
 *
 * A supplied sourceStatus owns retained-gate freshness; otherwise a fresh builder lint reads the source closure. The live authoring reader is evaluated before either compiler callback, even when sourceStatus ignores its arguments.
 *
 * @evidence contracts/common.md#principled-implementation The v1 protocol binds canonical snapshot and successful builder input identity. The project supplies fenced generated/state reads; graph values and generated records remain borrowed, and sequential reads can observe changing state. The utility supplies no publication fence, and current production commits do not consume this fingerprint.
 * @evidence contracts/common.md#clear-and-simple-design Snapshot construction records project-owned inputs once per observation, then delegates live-source admission and canonical hashing to readProductionPublicationInputFingerprint; no new lock or build-status owner is introduced.
 * @evidence contracts/common.md#prohibited-implementation-shortcuts Absent generated ownership refuses. A supplied source-status callback is trusted for currentness rather than secretly rerun; no quiet watcher or cached semantic manifest is described as proof of unchanged raw filesystem bytes.
 * @evidence contracts/common.md#meaningful-documentation States included identities, semantic-manifest versus exact-incarnation bytes, live-reader evaluation, optional retained status, non-atomic observation and current test-only consumption limits.
 * @evidence contracts/performance.md#efficient-algorithms For G generated members and graph population N, the snapshot copies entry arrays and rereads/hashes all member bytes; manifest JSON serialization and full canonical traversal/key ordering/hash add their complete byte/field cost. Without sourceStatus, source lint and all its dependency reads execute anew.
 * @evidence contracts/performance.md#reuse-equivalent-work The optional status provider may reuse an equivalent completed source gate after freshly validating its dependencies; the fallback builds anew. Generated bytes and project snapshot fields are always reobserved, and this function owns no cross-call memoization.
 * @evidence contracts/performance.md#bound-retention-and-release-resources Entry arrays, member digest records and canonical bytes are call-local while graph values and ownership remain borrowed. Project readers own descriptor release and the status provider owns retained gate state; no byte/population cap or background task is introduced here.
 */
export function productionPublicationInputFingerprint(
  project: AutoMovieProductionProject,
  currentAuthoringEvidence?: () => IAutoMovieProductionEvidence,
  sourceStatus?: () => IAutoMovieBuildProjectOutput
): string {
  const generated: IAutoMovieGeneratedManifest | null = project.generatedManifest();
  if (generated === null)
    throw new Error(
      "Terminal publication snapshot requires current builder-owned output.",
    );
  const projectState: ReturnType<AutoMovieProductionProject["projectStateRecords"]> = project.projectStateRecords();
  const graph: ReturnType<AutoMovieProductionProject["graph"]> = project.graph();
  const snapshot: Record<string, unknown> = {
    protocol: "automovie.terminal-publication-snapshot.v1",
    revision: project.revision(),
    incarnationDigest: digestAutoMovieBytes(projectState.incarnation),
    manifest: {
      value: project.manifest(),
      digest: digestAutoMovieBytes(
        Buffer.from(JSON.stringify(project.manifest()), "utf8"),
      ),
    },
    design: {
      production: graph.production,
      world: graph.world,
      models: [...graph.models],
      formations: [...graph.formations],
      shots: [...graph.shots],
      acceptance: [...graph.acceptance],
    },
    generated: {
      manifest: generated,
      files: generated.files.map((file: IAutoMovieGeneratedFile): { path: string; digest: string } => ({
        path: file.path,
        digest: digestAutoMovieBytes(project.readGeneratedFile(file.path)),
      })),
    },
  };
  return readProductionPublicationInputFingerprint({
    snapshot,
    currentAuthoringEvidence,
    compile:
      sourceStatus ??
      ((authoring: IAutoMovieProductionEvidence | undefined, current: (() => IAutoMovieProductionEvidence) | undefined): IAutoMovieBuildProjectOutput =>
        new AutoMovieProductionBuilder(project, authoring, current).lint({
          scope: "source",
        })),
  });
}
