import type { IAutoMovieBuildProjectInput, IAutoMovieBuildProjectOutput, IAutoMovieDiagnostic, IAutoMovieGeneratedFile, IAutoMovieGeneratedManifest } from "@automovie/interface";
import type { AutoMovieProductionProject } from "./AutoMovieProductionProject";
import { confirmAutoMovieBuildInputSnapshot } from "./confirmAutoMovieBuildInputSnapshot";
import type { materializeGeneratedFiles } from "./productionBuildArtifacts";
import { compareDiagnostics } from "./productionBuildDiagnostics";
import { AUTOMOVIE_PRODUCTION_BUILD_VERSION } from "./productionBuildProtocol";
import { statusesOf } from "./statusesOf";
import { publishAutoMovieGeneratedCompilation } from "./publishAutoMovieGeneratedCompilation";

/**
 * Confirm the observed compilation and publish only an admitted writable scope.
 *
 * Errors and design/lint scopes return no materialized files. Every return is
 * guarded by the current input observation, and source publication transfers
 * the complete file set atomically through the project authority.
 *
 * @evidence contracts/common.md#principled-implementation Sorted findings determine admission, current input identity confirms the observed revision before any outcome is returned, and the project publication guard atomically commits the complete source artifact set.
 * @evidence contracts/common.md#clear-and-simple-design One finalization phase owns outcome selection and publication dispatch; identity derivation and artifact validation have already completed, while project publication owns the physical transaction.
 * @evidence contracts/common.md#prohibited-implementation-shortcuts Errors never publish, read-only execution returns an empty materialized list, and changed input yields the snapshot refusal instead of an accepted old result.
 * @evidence contracts/common.md#meaningful-documentation States error/design/lint behavior, current-input guards and complete-set atomic publication ownership.
 * @evidence contracts/performance.md#efficient-algorithms For D diagnostics sorting takes O(D log D); generated status observation scales with entries and resident file bytes. Currentness recomputes its declared input projection, and writable success additionally serializes and publishes generated bytes once.
 * @evidenceExclude contracts/performance.md#reuse-equivalent-work Each finalization belongs to one effectful attempt; currentness is observed again before publication and an equivalent earlier effect is not replayed.
 * @evidence contracts/performance.md#bound-retention-and-release-resources Input maps and findings belong to the compilation; publication takes file ownership only through its guarded transaction and owns temporary-file cleanup. This phase retains no handle or independent task.
 */
export function finishAutoMovieProductionBuild(props: {
  project: AutoMovieProductionProject;
  input: IAutoMovieBuildProjectInput;
  materialize: boolean;
  diagnostics: IAutoMovieDiagnostic[];
  inputCurrent: () => boolean;
  inputFingerprint: string;
  inputRevision: number;
  files: ReturnType<typeof materializeGeneratedFiles> | null;
  manifest: IAutoMovieGeneratedManifest | null;
  entries: IAutoMovieGeneratedFile[];
}): IAutoMovieBuildProjectOutput {
  const { project, input, materialize, diagnostics, inputCurrent, inputFingerprint, inputRevision, files, manifest, entries }: typeof props = props;
    diagnostics.sort(compareDiagnostics);
    const confirmInputSnapshot: () => IAutoMovieBuildProjectOutput | null = (): IAutoMovieBuildProjectOutput | null =>
      confirmAutoMovieBuildInputSnapshot({
        authority: project,
        diagnostics,
        inputCurrent,
        inputFingerprint,
        inputRevision,
      });
    if (diagnostics.some((diagnostic: IAutoMovieDiagnostic): boolean => diagnostic.category === "error"))
      return (
        confirmInputSnapshot() ?? {
          success: false,
          revision: inputRevision,
          builder: {
            version: AUTOMOVIE_PRODUCTION_BUILD_VERSION,
            inputFingerprint,
          },
          diagnostics,
          materialized: [],
        }
      );
    if (input.scope === "design")
      return (
        confirmInputSnapshot() ?? {
          success: true,
          revision: inputRevision,
          builder: {
            version: AUTOMOVIE_PRODUCTION_BUILD_VERSION,
            inputFingerprint,
          },
          diagnostics,
          materialized: [],
        }
      );

    const sourceFiles: NonNullable<typeof files> = files!;
    const sourceManifest: IAutoMovieGeneratedManifest = manifest!;
    const materialized: ReturnType<typeof statusesOf> = statusesOf(project, entries);
    if (materialize === false)
      return (
        confirmInputSnapshot() ?? {
          success: true,
          revision: inputRevision,
          builder: {
            version: AUTOMOVIE_PRODUCTION_BUILD_VERSION,
            inputFingerprint,
          },
          diagnostics,
          materialized: [],
        }
      );
    return publishAutoMovieGeneratedCompilation({
      authority: project,
      publication: {
        files: sourceFiles,
        manifest: sourceManifest,
        inputCurrent,
        inputRevision,
      },
      inputFingerprint,
      diagnostics,
      materialized,
    });


}
