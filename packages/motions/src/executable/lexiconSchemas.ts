import type {
  IAutoMovieMotionHumanActionParams,
  IAutoMovieMotionHumanLexiconParams,
} from "@automovie/interface";

import fs from "node:fs";
import path from "node:path";
import typia from "typia";
import { HUMAN_LEXICON_FAMILIES } from "../lexicon/HUMAN_LEXICON_FAMILIES";
import HUMAN_SCHEMA_METADATA from "./HUMAN_SCHEMA_METADATA.json";
import { HumanSchemaMetadata } from "./HumanSchemaMetadata";

/**
 * Writes `src/lexicon/HUMAN_LEXICON_SCHEMA_DATA.ts`: the JSON schema of every
 * lexicon row's open parameters, by the row's registered name, and of every
 * action's parameters, by the action's name (`actions`), generated by
 * typia from interface's canonical parameter maps, then refined with the
 * motions-owned numeric admission metadata. Every metadata path must still
 * name a compatible canonical field or generation fails before writing.
 * It is a module, not a JSON file: a JSON file beside
 * `HUMAN_LEXICON_SCHEMAS.ts` would be what Node resolves the module's
 * extensionless import to where no compiled `.js` sits beside it. Run by
 * `pnpm --filter @automovie/motions schemas`, which compiles this entry with
 * the typia transform; the first argument, when given, is the file to write
 * instead.
 *
 * @evidence contracts/development/common.md#meaningful-documentation States what is written, from what, by which command, and the argument.
 * @evidence contracts/development/implementation.md#principled-implementation typia reads canonical structural contracts; HumanSchemaMetadata restores the captured integer, bound, default and unit rules after each row's fixed-key projection. Branches are matched structurally and missing fields reject stale metadata. Runtime records supply registered names only.
 * @evidence contracts/development/implementation.md#clear-and-simple-structure Generate, walk the families' namespaces, write.
 * @evidence contracts/development/implementation.md#prohibited-implementation-shortcuts Nothing is edited by hand: the file says which command writes it. Two laws of one family exported under one name, or two rows of one name, stop the generation with both named.
 * @evidenceExclude contracts/development/implementation.md#efficient-algorithms One generation per run.
 * @evidenceExclude contracts/development/implementation.md#reuse-equivalent-work Nothing to cache.
 * @evidenceExclude contracts/development/implementation.md#bound-retention-and-release-resources Runs once and exits.
 */
export function lexiconSchemas(target?: string): void {
  const collection: ReturnType<typeof typia.json.schemas> =
    typia.json.schemas<
      [IAutoMovieMotionHumanLexiconParams, IAutoMovieMotionHumanActionParams]
    >();
  type ISchema = { $ref?: string; properties?: Record<string, ISchema> };
  const components: Record<string, ISchema> = (collection.components.schemas ??
    {}) as Record<string, ISchema>;
  const resolved = (schema: ISchema | undefined): ISchema | undefined =>
    schema?.$ref === undefined
      ? schema
      : components[schema.$ref.split("/").at(-1)!];
  const families: Record<string, ISchema> =
    resolved(collection.schemas[0] as ISchema)?.properties ?? {};

  // Each export that plans, paired with the law it holds and so with the name the row is registered under.
  const rows: Map<string, ISchema> = new Map();
  for (const [family, spaces] of Object.entries(HUMAN_LEXICON_FAMILIES)) {
    const exports: Record<string, ISchema> =
      resolved(families[family])?.properties ?? {};
    const seen: Map<string, string> = new Map();
    for (const space of spaces as readonly object[])
      for (const [key, member] of Object.entries(space)) {
        if (
          typeof member !== "object" ||
          member === null ||
          !("plan" in member)
        )
          continue;
        const name: string = (member as { name: string }).name;
        if (seen.has(key) && seen.get(key) !== name)
          throw new Error(
            `${family}: two laws are exported as ${key} (${seen.get(key)} and ${name}); give one another export name`,
          );
        seen.set(key, name);
        if (
          rows.has(name) &&
          JSON.stringify(rows.get(name)) !== JSON.stringify(exports[key])
        )
          throw new Error(
            `two rows are named ${name} with different parameters`,
          );
        if (exports[key] !== undefined) rows.set(name, exports[key]!);
      }
  }
  const sorted = (entries: Map<string, ISchema>): Record<string, ISchema> =>
    Object.fromEntries(
      [...entries.entries()].sort(
        (a: [string, ISchema], b: [string, ISchema]): number =>
          a[0].localeCompare(b[0]),
      ),
    );
  const actions: Record<string, ISchema> = sorted(
    new Map(
      Object.entries(
        resolved(collection.schemas[1] as ISchema)?.properties ?? {},
      ),
    ),
  );
  const metadata: HumanSchemaMetadata.ICollection = HUMAN_SCHEMA_METADATA;
  if (metadata.version !== 1)
    throw new Error(
      `Unsupported Human schema metadata version ${metadata.version}`,
    );
  const boundaries: {
    actions: Record<string, ISchema>;
    rows: Record<string, ISchema>;
  } = { actions, rows: sorted(rows) };
  for (const kind of ["actions", "rows"] as const) {
    for (const name of Object.keys(metadata[kind]))
      if (!(name in boundaries[kind]))
        throw new Error(
          `${kind}.${name}: metadata names a removed parameter boundary`,
        );
    for (const [name, schema] of Object.entries(boundaries[kind])) {
      const tree: HumanSchemaMetadata.ITree | undefined = metadata[kind][name];
      if (!tree)
        throw new Error(
          `${kind}.${name}: declare its numeric admission metadata, using an empty object when it has no refinements`,
        );
      HumanSchemaMetadata.apply(schema, tree, components, `${kind}.${name}`);
    }
  }
  const generated: object = {
    $comment:
      "Written by `pnpm --filter @automovie/motions schemas` from the lexicon laws' parameter types (src/executable/lexiconSchemas.ts); do not edit by hand.",
    version: collection.version,
    rows: boundaries.rows,
    actions,
    components: collection.components,
  };
  const text: string = JSON.stringify(generated, null, 2);
  fs.writeFileSync(
    target ?? path.join(__dirname, "../lexicon/HUMAN_LEXICON_SCHEMA_DATA.ts"),
    [
      "// Written by `pnpm --filter @automovie/motions schemas` from the lexicon laws' parameter types (src/executable/lexiconSchemas.ts); do not edit by hand.",
      'import type { IAutoMovieMotionHumanLexiconSchemas } from "@automovie/interface";',
      "",
      "/**",
      " * The generated schemas as data: OpenAPI 3.1 JSON schemas of every lexicon",
      " * row's and every action's parameters, as one typed constant the package",
      " * and the website read through `HUMAN_LEXICON_SCHEMAS`.",
      " *",
      " * @evidence contracts/development/common.md#meaningful-documentation States what the data is and who reads it.",
      " * @evidence contracts/development/design.md#principled-representation The JSON schemas as one typed object, written by the generator.",
      " * @evidence contracts/development/design.md#minimal-and-owned-surface One constant, read by `HUMAN_LEXICON_SCHEMAS`.",
      " * @evidence contracts/development/design.md#prohibited-design-shortcuts Nothing is written by hand; a stale file fails CI.",
      " */",
      `export const HUMAN_LEXICON_SCHEMA_DATA: IAutoMovieMotionHumanLexiconSchemas.ICollection = ${text};`,
      "",
    ].join("\n"),
  );
}

lexiconSchemas(process.argv[2]);
