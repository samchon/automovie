import type {
  IAutoMovieImage,
  IAutoMovieMaterial,
  IAutoMovieMesh,
  IAutoMovieModelPart,
} from "@automovie/interface";

import type { IAutoMovieHumanParameters } from "../structures/IAutoMovieHumanParameters";
import { AutoMovieHumanIrisColor } from "../typings/AutoMovieHumanIrisColor";
import { AutoMovieHumanEyeball } from "./AutoMovieHumanEyeball";
import { AutoMovieHumanIrisImage } from "./AutoMovieHumanIrisImage";
import type { IAutoMovieHumanAppearanceBody } from "./IAutoMovieHumanAppearanceBody";

/**
 * Human appearance: the parts, materials and generated images that dress
 * the neutral body, appended to its model by the public generator.
 *
 * Every output is generated by code from the parameters and the body's
 * frames; no image or mesh data is stored. Part ids:
 *
 * - `human.eye.<side>.sclera`, `human.eye.<side>.iris`,
 *   `human.eye.<side>.cornea` for `side` in `left`, `right`.
 *
 * Material ids start with `human.eye.`; image ids with `human.eye.iris.`.
 * None of these collide with the body's `human.skin.` and
 * `human.construction.` namespaces, so the outputs concatenate onto the
 * body model's lists unchanged.
 *
 * Current consumption: `pigmentation.iris` selects the iris image; an
 * omitted `pigmentation` uses brown, the most common iris colour among
 * adults worldwide (a population convention for an unspecified input, not
 * an inference about the person).
 */
export namespace AutoMovieHumanAppearance {
  /** Appearance outputs to append to the body model. */
  export interface IOutput {
    /** Mesh parts in model metres. */
    parts: IAutoMovieModelPart[];

    /** Materials the parts cite. */
    materials: IAutoMovieMaterial[];

    /** Generated images the materials cite. */
    images: IAutoMovieImage[];
  }

  /**
   * Generate appearance for one parameter set on one generated body.
   *
   * @param params Complete public input
   * @param body Frames the body generator publishes for appearance
   * @returns Parts, materials and images to append to the body model
   */
  export function generate(
    params: IAutoMovieHumanParameters,
    body: IAutoMovieHumanAppearanceBody,
  ): IOutput {
    const iris: AutoMovieHumanIrisColor =
      params.pigmentation?.iris ?? AutoMovieHumanIrisColor.Brown;
    const image: IAutoMovieImage = AutoMovieHumanIrisImage.generate(iris);

    const parts: IAutoMovieModelPart[] = [];
    for (const side of ["left", "right"] as const) {
      // The right eye turns the shared iris image by an irrational-looking
      // fraction of a turn so the two irises do not repeat each other.
      const eye: AutoMovieHumanEyeball.IOutput = AutoMovieHumanEyeball.generate(
        {
          eye: body.eyePair[side],
          uvTurn: side === "left" ? 0 : 0.381966,
        },
      );
      parts.push(
        part(`human.eye.${side}.sclera`, "human.eye.sclera", eye.sclera),
        part(`human.eye.${side}.iris`, "human.eye.iris", eye.iris),
        part(`human.eye.${side}.cornea`, "human.eye.cornea", eye.cornea),
      );
    }

    return {
      parts,
      materials: AutoMovieHumanEyeball.materials(image.id),
      images: [image],
    };
  }
}

/**
 * Unattached mesh part.
 *
 * @param id Part id, also its name
 * @param material Material id
 * @param mesh Mesh in model metres
 * @returns The part
 */
function part(
  id: string,
  material: string,
  mesh: IAutoMovieMesh,
): IAutoMovieModelPart {
  return {
    id,
    name: id,
    geometry: { type: "mesh", mesh },
    material,
    attachedBone: null,
    transform: null,
  };
}
