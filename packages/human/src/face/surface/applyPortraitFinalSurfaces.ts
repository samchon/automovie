import { areaWeightedNormals } from "../../common/mesh/areaWeightedNormals";
import type { IControlMesh } from "../mesh/structures/IControlMesh";
import type { IPortraitFinalSurface } from "./structures/IPortraitFinalSurface";
import type { IPortraitFinalSurfaceHost } from "./structures/IPortraitFinalSurfaceHost";

/**
 * Collect final component surfaces before applying any of their positions.
 * Every provider reads the same deeply immutable snapshot, so reordering two
 * independent parts cannot make one fit against the other's edited surface.
 * Each returned proposal is copied before the next provider runs. Matching
 * requests may share an attachment; incompatible ownership of one vertex is
 * refused instead of selecting a winner by component order.
 *
 * This operation preserves vertex/triangle/material identities and leaves
 * normals to the assembler's one common recomputation afterward. Empty providers
 * or empty proposals retain the original mesh. It owns composition and numeric
 * admission, while each part owns its section geometry and boundary derivatives.
 * Positions and proposals are portrait millimetres; exact equality decides
 * shared ownership. Other mesh fields are retained, so any position-dependent
 * derived attributes must be regenerated by their downstream owner.
 *
 * @evidence contracts/common.md#principled-implementation Every provider receives one deeply frozen position/topology/normal snapshot; proposals are copied immediately and a resident-vertex map rejects incompatible exact targets before applying any position.
 * @evidence contracts/common.md#clear-and-simple-design This coordinator owns snapshot and proposal composition; providers own anatomy and the head assembler owns final normals and material packing.
 * @evidence contracts/common.md#prohibited-implementation-shortcuts Conflicting targets refuse rather than choosing an order-dependent winner or approximate weld; provider side effects outside the frozen host remain their responsibility.
 * @evidence contracts/common.md#meaningful-documentation Prose specifies millimetres, exact ownership equality, unchanged empty cases, retained identities and invalidation of derived attributes.
 * @evidence contracts/performance.md#efficient-algorithms Snapshot and area normals cost O(V+T); provider work adds its actual cost, proposal composition is O(P), and a nonempty result copies O(V) positions.
 * @evidence contracts/performance.md#reuse-equivalent-work One immutable snapshot and normal field serve every provider in the call; no changed-surface proposal or effectful callback is reused across builds.
 * @evidence contracts/performance.md#bound-retention-and-release-resources Snapshot, copied proposals and ownership map scale with mesh and proposal populations during the call; only resulting position rows escape and no global task or cache is retained.
 */
export function applyPortraitFinalSurfaces(
  mesh: IControlMesh,
  surfaces: readonly { id: string; propose: IPortraitFinalSurface }[],
): IControlMesh {
  if (surfaces.length === 0) return mesh;
  if (
    surfaces.some((surface: { id: string; propose: IPortraitFinalSurface }): boolean => surface.id.trim().length === 0) ||
    new Set(surfaces.map((surface: { id: string; propose: IPortraitFinalSurface }): string => surface.id)).size !== surfaces.length
  )
    throw new Error("Final surface providers need unique nonempty identities.");
  const host: IPortraitFinalSurfaceHost = Object.freeze({
    positions: Object.freeze(
      mesh.positions.map((point: number[]): readonly number[] => Object.freeze([...point])),
    ),
    indices: Object.freeze([...mesh.indices]),
    groups: Object.freeze([...mesh.groups]),
    normals: Object.freeze(
      areaWeightedNormals(mesh.positions.flat(), mesh.indices),
    ),
  });
  const proposals: { id: string; vertices: { vertex: number; target: number[] }[] }[] = surfaces.map((surface: { id: string; propose: IPortraitFinalSurface }): { id: string; vertices: { vertex: number; target: number[] }[] } => ({
    id: surface.id,
    vertices: surface
      .propose(host)
      .map(({ vertex, target }: { vertex: number; target: readonly number[] }): { vertex: number; target: number[] } => ({ vertex, target: [...target] })),
  }));
  const targets: Map<number, { owner: string; point: number[] }> = new Map<number, { owner: string; point: number[] }>();
  for (const proposal of proposals)
    for (const { vertex, target } of proposal.vertices) {
      if (
        !Number.isInteger(vertex) ||
        vertex < 0 ||
        vertex >= mesh.positions.length ||
        target.length !== 3 ||
        !target.every(Number.isFinite)
      )
        throw new Error(
          "A final surface proposal needs a resident vertex and finite XYZ.",
        );
      const previous: { owner: string; point: number[] } | undefined = targets.get(vertex);
      if (
        previous !== undefined &&
        previous.point.some((value: number, axis: number): boolean => value !== target[axis])
      )
        throw new Error(
          `Incompatible final surface ownership at vertex ${vertex}: ${previous.owner}/${proposal.id}.`,
        );
      targets.set(vertex, { owner: proposal.id, point: target });
    }
  if (targets.size === 0) return mesh;
  return {
    ...mesh,
    positions: mesh.positions.map(
      (point: number[], id: number): number[] => targets.get(id)?.point ?? [...point],
    ),
    indices: mesh.indices,
    groups: mesh.groups,
  };
}
