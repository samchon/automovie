import type { IPortraitHairShape } from "./IPortraitHairShape";
import { createPortraitHairFibreTexture } from "./createPortraitHairFibreTexture";

/**
 * Generate an RGB tangent-space normal PNG from the same fibre coverage that owns the colour mask. Across each winning fibre a circular cross-section supplies X and Z; Y is neutral in the legacy pattern. A curl profile rotates that transverse normal perpendicular to its wave tangent using the authored nominal aspect ratio. Empty samples retain the flat card normal. This shading detail adds no vertices and does not model hair scattering. The fibres are the mask's own, generated by the one shared owner, so an optional greying mixture has to reach both: an unpigmented fibre is painted thicker and the relief must describe the same fibre the colour does.
 *
 * @evidence contracts/common.md#principled-implementation The shared fibre raster emits relief from its winning coverage fibre and optional curl tangent.
 * @evidence contracts/common.md#clear-and-simple-design This wrapper selects RGB normal output without a second fibre layout algorithm.
 * @evidence contracts/common.md#prohibited-implementation-shortcuts Relief is shading detail, adds no geometry and models neither physical scattering nor collision freedom.
 * @evidence contracts/common.md#meaningful-documentation Grey mixture reaches the same raster owner so its thicker painted white fibres match colour coverage.
 * @evidence contracts/performance.md#efficient-algorithms Work is the shared RGB raster's pixel times fibre loop and PNG encoding.
 * @evidence contracts/performance.md#reuse-equivalent-work The wrapper reuses the canonical fibre generator; no normal-image cache is maintained.
 * @evidence contracts/performance.md#bound-retention-and-release-resources Only the self-contained data URI escapes, with raster temporaries released after generation.
 */
export function createPortraitHairNormalTexture(
  seed: number,
  fibres: number,
  coverage: number,
  curl?: IPortraitHairShape["fibreCurl"],
  mixture?: { pigment: readonly number[]; grey: number },
): string {
  return createPortraitHairFibreTexture(
    seed,
    fibres,
    coverage,
    true,
    curl,
    1,
    mixture,
  );
}
