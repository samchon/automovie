import type { HumanCurveFamily } from "../internal/HumanCurveFamily";
import type { HumanSurface } from "../internal/HumanSurface";
import { evaluateAutoMovieBernstein64 } from "@automovie/engine/geometry/curve";
import { HumanTrunkShapeSpline } from "./HumanTrunkShapeSpline";
import { HumanTrunkFeatureLaw } from "./HumanTrunkFeatureLaw";
import { HumanTrunkWholeRules } from "./HumanTrunkWholeRules";

/** Joint vector family in the common physical source gauge.
 * Native five-plane values and first jets are shared unknowns fitted to all
 * original profiles. A native boundary is the identical object in both adjacent
 * restrictions. No old radial curve, patch or bridge supplies a second end.
 * Requires the jointly refitted midpoint bundle: channels24..39 are C/Q,
 * where C is the actual original feature-arc t=.5 position, not B/Q.
 */
export namespace HumanTrunkWholeFamily {
  type V = HumanCurveFamily.Vector;
  type S = readonly [number, number, number];
  type Section = HumanTrunkFeatureLaw.Section;

  /** One common source gauge supplied by the skeleton and native scalar owner. */
  export interface Input {
    /** Hip, highHip, waist, underbust, chest physical Y, mm and increasing. */
    nativeStationsMm: readonly [number, number, number, number, number];
    /** Fixed source-reference pelvis support, mm; not generated-world pelvis. */
    pelvisReferenceMm: V;
    /** Actual native Hip control, mm; not skin or course-polygon perimeter. */
    nativeHipGirthMm: number;
    /** Achieved shape in [-1,1]; cohort prediction and physical causality differ. */
    shape: number;
    /** Sole scalar owner's Q, dQ/dY, d²Q/dY² in the same physical gauge. */
    nativeGirthJet: (stationMm: number) => readonly [number, number, number];
  }

  /** Shared native or approximate class-event principal without radial metadata. */
  export interface Principal {
    /** Stable native/event identity, never a specimen identifier. */
    id: string;
    /** Physical source-gauge Y, mm. */
    stationMm: number;
    /** Complete vector primitive and exact station/phase jets at this boundary. */
    section: Section;
    /** Eight actual local-t boundary objects shared by both adjacent restrictions. */
    arcBoundaries: readonly HumanSurface.Boundary[];
  }

  /** A restriction of the owning function; refinement introduces no shape fit. */
  export interface Interval {
    /** Sole boundary object for the lower physical station. */
    start: Principal;
    /** Sole boundary object for the upper physical station. */
    end: Principal;
    /** Evaluate only inside this closed physical interval. */
    jet: (stationMm: number, phaseRadians: number) => HumanCurveFamily.Jet;
    /** Derive one exact midpoint and return two restrictions sharing it. */
    subdivide: () => readonly [Interval, Interval];
    /** Eight separate feature-arc patches; a C0 is an edge, never crossed. */
    patches: readonly HumanSurface.Patch[];
  }

  /** Full native-domain authority, with the first interval's source feature scope. */
  export interface Family {
    /** Physical source-gauge support [Hip Y, chest Y], mm. */
    domainMm: readonly [number, number];
    /** Exactly five native curves, generated by the same vector function. */
    nativePrincipals: readonly Principal[];
    /** Native planes plus the generated lower-crease death event. */
    principals: readonly Principal[];
    /** Restrictions share their exact principal objects and analytic function. */
    intervals: readonly Interval[];
    /** Complete hip-to-highHip restriction, consuming the same shared highHip. */
    hipToHighHip: Interval;
    /** Full section authority; arbitrary stations do not become fitting layers. */
    section: (stationMm: number) => Section;
    /** Canonical radians mean fixed feature address psi, not geometric polar angle. */
    canonicalPhaseMeaning: "fixed-feature-address-radians";
    /** Full analytic jet at fixed feature psi=2*pi*(arc+t)/8. */
    jet: (stationMm: number, phaseRadians: number) => HumanCurveFamily.Jet;
    /** Separate normalized-physical-phase phi=2*pi*p/L jet with quotient rule. */
    physicalPhaseJet: (stationMm: number, physicalPhaseRadians: number) => HumanCurveFamily.Jet;
    /** Eight chart restrictions per native/event interval, with shared boundaries. */
    patches: readonly HumanSurface.Patch[];
    /** Source/data/representation qualifications carried with the family. */
    limitations: readonly string[];
  }

  /** Construct all C2 channels once, reusing the existing minimum-jerk solver.
   * The scalar owner's callback is consumed unchanged. Forty shared shape
   * channels and eight physical-width channels have native five-plane values
   * and first jets. Per query the exact product rule supplies second jets.
   * The five native principals, one event and at most one arbitrary section
   * remain cached; no specimen mesh, source curve or unbounded cache is held.
   */
  export function build(input: Input): Family {
    if (HumanTrunkWholeRules.fieldRepresentation !== "actual-feature-arc-midpoint-v1")
      throw new Error("The paired actual-intermediate-curve coefficient bundle is required");
    const source: Input = { ...input, nativeStationsMm: [...input.nativeStationsMm],
      pelvisReferenceMm: [...input.pelvisReferenceMm] };
    const ys: readonly number[] = source.nativeStationsMm;
    if (ys.length !== 5 || ys.some((y: number, i: number): boolean => !Number.isFinite(y) || (i > 0 && y <= ys[i - 1]!)) ||
      !Number.isFinite(source.shape) || source.shape < -1 || source.shape > 1 || !(source.nativeHipGirthMm > 0) ||
      !Number.isFinite(source.nativeHipGirthMm) || source.pelvisReferenceMm.length !== 3 ||
      !source.pelvisReferenceMm.every(Number.isFinite))
      throw new Error("One finite ordered native trunk source gauge required");
    const span: number = ys[4]! - ys[0]!;
    const knots: number[] = ys.map((y: number): number => (y - ys[0]!) / span);
    const make: (c: readonly (readonly number[])[]) => HumanTrunkShapeSpline.Curve = (
      c: readonly (readonly number[])[],
    ): HumanTrunkShapeSpline.Curve => {
      if (c.length !== 10 || c.some((p: readonly number[]): boolean => p.length !== 2 || !p.every(Number.isFinite)))
        throw new Error("Complete common five-plane value/first-jet coefficients required");
      const v: number[] = c.map((p: readonly number[]): number => p[0]! + source.shape * p[1]!);
      return HumanTrunkShapeSpline.build(knots, v.slice(0, 5), v.slice(5));
    };
    const curves: HumanTrunkShapeSpline.Curve[] = HumanTrunkWholeRules.channels.map(make);
    const widthCurves: HumanTrunkShapeSpline.Curve[] = HumanTrunkWholeRules.widthChannels.map(make);
    const death: number = source.pelvisReferenceMm[1] + source.nativeHipGirthMm *
      (HumanTrunkWholeRules.deathMuAffine[0]! + source.shape * HumanTrunkWholeRules.deathMuAffine[1]!);
    if (!Number.isFinite(death) || death <= ys[0]! || death >= ys[1]!)
      throw new Error("Lower-crease death must precede the common highHip boundary");
    const directions: readonly (readonly [number, number])[] = [
      [1, 0], [Math.SQRT1_2, Math.SQRT1_2], [0, 1], [-Math.SQRT1_2, Math.SQRT1_2],
      [-1, 0], [-Math.SQRT1_2, -Math.SQRT1_2], [0, -1], [Math.SQRT1_2, -Math.SQRT1_2],
    ];
    const sample: (curve: HumanTrunkShapeSpline.Curve, x: number) => S = (
      curve: HumanTrunkShapeSpline.Curve, x: number,
    ): S => {
      const v: readonly number[] = HumanTrunkShapeSpline.sample(curve, x);
      return [v[0]!, v[1]! / span, v[2]! / (span * span)];
    };
    const construct: (stationMm: number) => Section = (stationMm: number): Section => {
      if (!Number.isFinite(stationMm) || stationMm < ys[0]! || stationMm > ys[4]!)
        throw new Error("Whole vector trunk query lies outside the native physical domain");
      const x: number = (stationMm - ys[0]!) / span;
      const q: S = source.nativeGirthJet(stationMm);
      if (q.length !== 3 || !q.every(Number.isFinite) || q[0] <= 0)
        throw new Error("The shared native-girth owner returned an unsupported scalar jet");
      const values: S[] = curves.map((c: HumanTrunkShapeSpline.Curve): S => sample(c, x));
      const widthValues: S[] = widthCurves.map((c: HumanTrunkShapeSpline.Curve): S => product(q, sample(c, x)));
      const positions: V[][] = [[], [], []];
      const left: V[][] = [[], [], []];
      const right: V[][] = [[], [], []];
      const midpoints: V[][] = [[], [], []];
      const contrast: readonly V[] = lowerContrast(source, stationMm, death);
      for (let i: number = 0; i < 8; i++) {
        const radius: S = product(q, values[i]!);
        if (!(radius[0] > 0 && widthValues[i]![0] > 0))
          throw new Error("A common guide node or phase width left its positive branch");
        const cx: S = product(q, values[24 + 2 * i]!);
        const cz: S = product(q, values[25 + 2 * i]!);
        for (let order: number = 0; order < 3; order++) {
          positions[order]!.push([
            radius[order]! * directions[i]![0] + (order === 0 ? source.pelvisReferenceMm[0] : 0),
            order === 0 ? stationMm : order === 1 ? 1 : 0,
            radius[order]! * directions[i]![1] + (order === 0 ? source.pelvisReferenceMm[2] : 0),
          ]);
          const ux: number = values[8 + 2 * i]![order]!;
          const uz: number = values[9 + 2 * i]![order]!;
          const a: V = i === 4 ? contrast[order]! : [0, 0, 0];
          left[order]!.push([ux + a[0], 0, uz + a[2]]);
          right[order]!.push([ux - a[0], 0, uz - a[2]]);
          midpoints[order]!.push([
            cx[order]! + (order === 0 ? source.pelvisReferenceMm[0] : 0),
            order === 0 ? stationMm : order === 1 ? 1 : 0,
            cz[order]! + (order === 0 ? source.pelvisReferenceMm[2] : 0),
          ]);
        }
      }
      return HumanTrunkFeatureLaw.fromMidpoints({ positions, left, right, midpoints,
        widths: widthValues, mu: (stationMm - source.pelvisReferenceMm[1]) / source.nativeHipGirthMm,
        withinObservedMuEnvelope: (stationMm - source.pelvisReferenceMm[1]) / source.nativeHipGirthMm >= HumanTrunkWholeRules.observedMuBounds[0]! &&
          (stationMm - source.pelvisReferenceMm[1]) / source.nativeHipGirthMm <= HumanTrunkWholeRules.observedMuBounds[1]!,
        posteriorEvent: { deathStationMm: death, featureClass: stationMm < death ? "C0" : "G1" },
      });
    };
    const names: readonly string[] = ["hip", "highHip", "waist", "underbust", "chest"];
    const principal: (id: string, y: number, s: Section) => Principal = (
      id: string, y: number, s: Section,
    ): Principal => ({
      id, stationMm: y, section: s,
      arcBoundaries: Array.from({ length: 8 }, (_unused: unknown, i: number): HumanSurface.Boundary => ({
        id: id + ".arc." + i, unit: "normalized", start: 0, end: 1,
        evaluate: (t: number): V => s.localJet(i, t).positionMm,
        derivative: (t: number): V => s.localJet(i, t).derivativeT,
      })),
    });
    const native: Principal[] = ys.map((y: number, i: number): Principal =>
      principal("trunk." + names[i]!, y, construct(y)));
    const event: Principal = principal("trunk.posterior.death", death, construct(death));
    const principals: Principal[] = [...native, event].sort((a: Principal, b: Principal): number => a.stationMm - b.stationMm);
    let last: Principal | undefined;
    const section: (y: number) => Section = (y: number): Section => {
      const existing: Principal | undefined = principals.find((p: Principal): boolean => p.stationMm === y);
      if (existing) return existing.section;
      if (last?.stationMm === y) return last.section;
      last = principal("trunk.restriction", y, construct(y));
      return last.section;
    };
    const interval: (start: Principal, end: Principal) => Interval = (
      start: Principal, end: Principal,
    ): Interval => {
      const at: (y: number) => Section = (y: number): Section => {
        if (!Number.isFinite(y) || y < start.stationMm || y > end.stationMm)
          throw new Error("Query lies outside the owning restriction");
        return y === start.stationMm ? start.section : y === end.stationMm ? end.section : section(y);
      };
      const edges: HumanSurface.Boundary[] = Array.from({ length: 8 }, (_unused: unknown, i: number): HumanSurface.Boundary => ({
        id: start.id + ".to." + end.id + ".feature." + i,
        unit: "mm", start: start.stationMm, end: end.stationMm,
        evaluate: (y: number): V => at(y).featureTraces[i]!.positionMm,
        derivative: (y: number): V => at(y).featureTraces[i]!.longitudinalDerivative,
      }));
      const patches: HumanSurface.Patch[] = Array.from({ length: 8 }, (_unused: unknown, i: number): HumanSurface.Patch => ({
        id: start.id + ".to." + end.id + ".arc." + i,
        u: { start: start.stationMm, end: end.stationMm, unit: "mm" },
        v: { start: 0, end: 1, unit: "normalized" }, outwardSign: 1,
        jet: (y: number, t: number): ReturnType<HumanSurface.Patch["jet"]> => {
          const j: HumanTrunkFeatureLaw.LocalJet = at(y).localJet(i, t);
          return { positionMm: j.positionMm, derivativeU: j.derivativeY, derivativeV: j.derivativeT };
        },
        boundaries: {
          u0: { curve: start.arcBoundaries[i]!, orientation: 1 },
          u1: { curve: end.arcBoundaries[i]!, orientation: 1 },
          v0: { curve: edges[i]!, orientation: 1 },
          v1: { curve: edges[(i + 1) % 8]!, orientation: 1 },
        },
      }));
      return { start, end, patches,
      jet: (y: number, phi: number): HumanCurveFamily.Jet => {
        return at(y).featureJet(phi);
      },
      subdivide: (): readonly [Interval, Interval] => {
        const y: number = (start.stationMm + end.stationMm) / 2;
        if (!(y > start.stationMm && y < end.stationMm)) throw new Error("Physical midpoint is unresolved");
        const midpoint: Principal = principal("trunk.restriction." + y, y, section(y));
        return [interval(start, midpoint), interval(midpoint, end)];
      },
      };
    };
    const intervals: Interval[] = principals.slice(1).map((p: Principal, i: number): Interval => interval(principals[i]!, p));
    return {
      domainMm: [ys[0]!, ys[4]!], nativePrincipals: native, principals,
      intervals, patches: intervals.flatMap((part: Interval): readonly HumanSurface.Patch[] => part.patches),
      hipToHighHip: interval(native[0]!, native[1]!), section,
      canonicalPhaseMeaning: "fixed-feature-address-radians",
      jet: (y: number, psi: number): HumanCurveFamily.Jet => section(y).featureJet(psi),
      physicalPhaseJet: (y: number, phi: number): HumanCurveFamily.Jet => section(y).evaluateRadians(phi),
      limitations: [
        "Common source-frame conditional fit; native scalar/observed course/skin perimeter remain distinct.",
        "Hip-to-highHip supports the source lower-C0 death graph and shares its highHip object with the upper restriction.",
        "Upper-back and other upper directional corners have unidentified common activation; the generated upper phase graph is G1.",
        "Independent physical-q causality, global embedding and generated-world boundary/render qualification remain separate.",
        "Ordinary phase joins share P and physical T; angular second/mixed jets are selected one-sided fields, not circumferential C2.",
        "Fixed-feature chart edges are G1 at ordinary nodes because their positive widths may differ; both sides are explicit.",
        "Patch and boundary coordinates remain in the declared source gauge; main must apply the common world affine transport before emission.",
        "Fixed-feature canonical radians are anatomical addresses, not polar angles; physical-phase radians use a separate moving-partition quotient.",
        "Original source off-plane C0 addresses and actual h remain in evidence; the common generated node lies on the shared sagittal plane.",
      ],
    };
  }

  /** Physical product rule through second station order. */
  function product(a: S, b: S): S {
    return [a[0] * b[0], a[1] * b[0] + a[0] * b[1], a[2] * b[0] + 2 * a[1] * b[1] + a[0] * b[2]];
  }

  /** Exact quintic lower contrast with zero value/first/second at death. */
  function lowerContrast(input: Input, y: number, death: number): readonly V[] {
    if (y >= death) return [[0, 0, 0], [0, 0, 0], [0, 0, 0]];
    const width: number = death - input.nativeStationsMm[0];
    const t: number = (y - input.nativeStationsMm[0]) / width;
    const m: number = (input.shape + 1) / 2;
    const c: V[] = HumanTrunkWholeRules.lowerContrast.map((ends: readonly (readonly number[])[]): V => [
      ends[0]![0]! * (1 - m) + ends[1]![0]! * m, 0,
      ends[0]![1]! * (1 - m) + ends[1]![1]! * m,
    ]);
    const controls: V[] = [c[0]!, c[1]!.map((v: number): number => v * 2 / 5) as V,
      c[2]!.map((v: number): number => v / 10) as V, [0, 0, 0], [0, 0, 0], [0, 0, 0]];
    return [0, 1, 2].map((order: number): V => {
      let a: V[] = controls;
      for (let k: number = 0; k < order; k++) {
        const degree: number = a.length - 1;
        a = a.slice(1).map((p: V, i: number): V => p.map((v: number, axis: number): number =>
          degree * (v - a[i]![axis]!) / width) as V);
      }
      const p: readonly number[] = evaluateAutoMovieBernstein64({
        primitive: "polynomialBezier", degree: a.length - 1, controls: a,
      }, t).point;
      return [p[0]!, p[1]!, p[2]!];
    });
  }
}
