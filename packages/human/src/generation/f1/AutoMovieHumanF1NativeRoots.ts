type IFields = IAutoMovieHumanF1NativeLaw.IFields;
type ISize = IAutoMovieHumanF1NativeLaw.ISize;
const { ARM, EXTREMITIES, LEG, RAIL, ratio, translated } = Calibration;

/** Actual source-stage inputs; this is not a partial assembled person. */
interface IContext {
  /** Closed all/tape candidate field request. */
  request: Build.Request;
  /** Borrowed complete original assembly and placed bone assembly. */
  original: IAutoMovieHumanF1.IAssembly;
  bone: IAutoMovieHumanF1.IAssembly;
  /** Same immutable original source controls and actual calibration. */
  originals: ReadonlyMap<string, IAutoMovieViewPart>;
  zero: IFields;
  /** Same immutable original endpoint datum for complete and tape construction. */
  projectionOwner: IAutoMovieHumanNativeProjectionCourse.IProjectionOwner;
  /** Already defined original trunk source, not a completed loft. */
  family: (name: keyof IAutoMovieHumanF1.IAssembly["body"]) => IAutoMovieHumanConicLoft.IFamily;
  /** Existing physical material station maps, filled by the same source builders. */
  maps: Map<string, { forward: (s: number) => number }>;
  /** Actual current source definitions generated by this stage. */
  generated: Map<keyof IAutoMovieHumanF1.IAssembly["body"], IAutoMovieHumanConicLoft.IFamily>;
  /** Existing qualified skin field used only by the retained leg/split owner. */
  skinPoint: (point: AutoMovieVector3Tuple) => AutoMovieVector3Tuple;
  /** Sole native source-target and exact site-protection constructors. */
  targets: (
    prior: IAutoMovieHumanConicLoft.IFamily,
    axis: IAutoMovieViewAxis.IAxis,
    scale: AutoMovieVector2Tuple,
    features: IAutoMovieLoftRelief[],
  ) => ReadonlyMap<string, IAutoMovieViewPart>;
  measured: (
    prior: IAutoMovieHumanConicLoft.IFamily,
    axis: IAutoMovieViewAxis.IAxis,
    features: IAutoMovieLoftRelief[],
    sites: readonly (readonly [number, AutoMovieVector2Tuple])[],
  ) => Native.ISpec["protection"];
}

/** Complete root-stage result, returned only after all independent source admission causes are collected. */
interface IResult {
  /** Shared port definitions for actual source identities. */
  rootPorts: Map<string, IAutoMovieHumanF1NativeRoot.IRootSpec>;
  /** Same range-independent course/seed candidates used by dependent cutters. */
  rootPrepared: Map<string, IAutoMovieHumanF1NativeRoot.IPrepared>;
  /** Same root owner transports actual scoped cutter material controls before search. */
  nativeSeed: (family: IAutoMovieHumanConicLoft.IFamily, seed: IAutoMovieHumanF1NativeRoot.ISeed, hostFace: string) => IAutoMovieConstructionSeed;
  /** Strict loop lookup from this same invocation's completed root definitions. */
  rootLoop: (
    name: "arm" | "breast" | "nose",
    side: 1 | -1,
  ) => IAutoMovieConstructionPortLoop;
  /** Invocation-local detached seed endpoint/mid observations, populated by construction. */
  seedControls: Map<string, IAutoMovieHumanF1NativeRoot.ISeedTransport>;
}

/** Generate all requested native root sources from the shared original definitions before dependent assembly. */
export function AutoMovieHumanF1NativeRoots(context: IContext): IResult {
  const {
    request,
    original,
    bone,
    originals,
    zero,
    projectionOwner,
    family,
    maps,
    generated,
    skinPoint,
    targets,
    measured,
  }: IContext = context;
  const fields: Build.Request["fields"] = request.fields;
  const identity: (s: number) => number = (s: number): number => s;
  const complete: () => IFields = (): IFields => {
    if (request.scope !== "all")
      throw new Error("unrequested candidate family construction");
    return request.fields;
  };
  const rootField: (name: keyof IFields["roots"]) => ISize = (
    name: keyof IFields["roots"],
  ): ISize =>
    name === "arm" || name === "breast"
      ? fields.roots[name]
      : complete().roots[name];
  const arm: () => Profile.IScale = (): Profile.IScale =>
    Profile.create(
      ARM.map(
        ([name, station]: readonly [keyof IFields["arm"], number]): readonly [
          number,
          AutoMovieVector2Tuple,
        ] => [
          name === "wrist"
            ? AutoMovieHumanF1ArmEnd.station(original.body.arm, original.body.hand)
            : station,
          ratio(complete().arm[name], zero.arm[name]),
        ],
      ),
    );

  // One jet-carrying profile down the leg and on to the foot's site: the ankle's ratio is held to its site,
  // then the endpoint-flat quintic reaches the foot's, as the former ankle switch read it.
  const leg: () => Profile.IScale = (): Profile.IScale =>
    Profile.create([
      ...LEG.map(
        ([name, station]: readonly [keyof IFields["leg"], number]): readonly [
          number,
          AutoMovieVector2Tuple,
        ] => [station, ratio(complete().leg[name], zero.leg[name])],
      ),
      [EXTREMITIES.foot, ratio(complete().extremities.foot, zero.extremities.foot)],
    ]);
  const rootPorts: Map<string, IAutoMovieHumanF1NativeRoot.IRootSpec> = new Map();
  const rootPrepared: Map<string, IAutoMovieHumanF1NativeRoot.IPrepared> = new Map();
  const rootFailures: string[] = [];
  /** Place the prepared nose on the current trunk wall for this candidate. */
  function prepareNose(): IAutoMovieHumanF1NativeRoot.IPrepared {
    if (request.scope !== "all")
      throw new Error("the tape scope has no nose root");
    if ("refusal" in request.nose) throw new Error(request.nose.refusal);
    const prepared: IAutoMovieHumanF1NativeRoot.IPrepared = Root.prepare(
      request.nose.calibration,
      H.source(family("trunk")),
      ratio(request.fields.roots.nose, zero.roots.nose),
    );
    rootPrepared.set(original.body.nose.name, prepared);
    return prepared;
  }
  const requestedRoots: readonly (keyof IFields["roots"])[] =
    request.scope === "tapes"
      ? (["breast"] as const)
      : (["arm", "leg", "breast", "nose"] as const);
  for (const name of requestedRoots) {
    try {
      const prior: IAutoMovieHumanConicLoft.IFamily = original.body[name],
        placed: IAutoMovieHumanConicLoft.IFamily = bone.body[name];
      const rootRatio: AutoMovieVector2Tuple = ratio(rootField(name), zero.roots[name]);
      const first: number = prior.knots[0]!;
      const rail: number = name === "arm"
        ? AutoMovieHumanJoinLoop.address(
            H.source(prior), [first, prior.knots.at(-1)!],
            original.point("upperarm"), first,
          )[0]
        : name === "breast" ? first : Calibration.rootStation(original, name);
      const originalRange: readonly [number, number] = name === "nose"
        ? AutoMovieHumanPeriodicRailRange(AutoMovieHumanF1RootRails.nose)
        : [rail - first, rail - first];
      const originalMinimum: number = name === "nose" ? first + originalRange[0] : rail;
      const originalMaximum: number = name === "nose" ? first + originalRange[1] : rail;
      // Only the nose continues to use a port. Side contacts are generated
      // when the person's actual trunk and limb sources have been declared.
      const prepared: IAutoMovieHumanF1NativeRoot.IPrepared | undefined =
        name === "nose" ? prepareNose() : undefined;
      const priorAxis: IAutoMovieViewAxis.IAxis = H.axis(prior);

      // The bone-placed course in material stations, and whether a segment length moved the arm's runs. Unmoved, the arm's skin root
      // is the original course carried by the root law, as before; moved, it is the person's own course carried the same way, so
      // root and bone keep one set of section planes through the handoff below.
      //
      // The leg's root is the pelvis's: its first ring stands 104 mm down its course, on the trunk's end, so the stretch up to the
      // handoff's middle is held (`AutoMovieHumanMaterialCourse.IHold`) and its skin root stays the original course on its skin
      // datum. Carried by the thigh's ratio from the hip centre instead, a thigh 0.9 times as long lifted that ring 10.4 mm into
      // the trunk's end and the split's band folded along the rail (a level light line across each thigh, round of 19:00).
      const legRelease: number =
        originalMaximum + Math.sqrt(rootField(name).depth * rootField(name).breadth) / 2;
      const boneAxis: IAutoMovieViewAxis.IAxis = LengthCourse.create(
        prior,
        placed,
        name === "leg"
          ? { station: (originalMaximum + legRelease) / 2, window: (legRelease - originalMaximum) / 2 }
          : undefined,
      );
      const skin: IAutoMovieViewAxis.IAxis =
        prepared !== undefined ? prepared.axis : name === "arm" ? boneAxis :
          translated(
            priorAxis,
            F.sub(skinPoint(priorAxis.at(0).origin), priorAxis.at(0).origin),
          );

      // The part's own scale past its root, as a station function with its jet (the native source applies it
      // to the source function, not at knots): the limb's site profile, or the root ratio for a rigid part.
      const own: Profile.IScale =
        name === "arm" ? arm() : name === "leg" ? leg() : Profile.constant(rootRatio);
      const forward: (s: number) => number = identity;
      // The builder admits only F1's own projection until the mound is one family, so this is the identity course.
      const course: IAutoMovieHumanNativeProjectionCourse.IPrepared | undefined = name === "breast"
        ? projectionOwner.project(originals.get(prior.name)!, skin, fields.breastProjection)
        : undefined;
      const sourceAxis: IAutoMovieViewAxis.IAxis = course?.axis ?? skin;

      // Semantic feature ownership is fixed on the original material scope,
      // before the edited rail/range is computed.
      const featureScale: (net: IAutoMovieLoftRelief) => AutoMovieVector2Tuple = (
        net: IAutoMovieLoftRelief,
      ): AutoMovieVector2Tuple =>
        (net.name === name + ".hollow.0" || (name === "nose" && net.name === "nose.side"))
          ? rootRatio
          : own((net.stations[0] + net.stations[1]) / 2);
      const features: IAutoMovieLoftRelief[] = AutoMovieHumanNativeFeatureLaw(
        prior.reliefs ?? [],
        placed.reliefs ?? [],
        featureScale,
        forward,
      );
      const rootTargets: ReadonlyMap<string, IAutoMovieViewPart> =
        targets(prior, sourceAxis, rootRatio, features);
      let minimumRail: number = originalMinimum;
      let maximumRail: number = originalMaximum;
      if (prepared !== undefined && request.scope === "all") {
        const primary: IAutoMovieHumanF1NativeRoot.IRootSpec = prepared.resolve(rootTargets.get(prior.name)!);
        rootPorts.set(prior.name, primary);
        minimumRail = primary.range[0];
        maximumRail = primary.range[1];
      }
      const rootSize: ISize = rootField(name);
      const release: number =
        maximumRail + Math.sqrt(rootSize.depth * rootSize.breadth) / 2;
      const axis: IAutoMovieViewAxis.IAxis =
        name === "arm" || name === "leg"
          ? N.root(skin, boneAxis, maximumRail, release)
          : course?.axis ?? N.skinCourse(skin);
      // The root ratio is handed over to the limb's profile between the rail and the release; a rigid part
      // keeps the root ratio at every station.
      const scales: Profile.IScale =
        name === "arm" || name === "leg"
          ? Profile.handoff(Profile.constant(rootRatio), own, maximumRail, release)
          : Profile.constant(rootRatio);
      const requirements: N.IProtection[] =
        name === "nose"
          ? [{ type: "interval", domain: [minimumRail, maximumRail] }]
          : [
              {
                type: "junction",
                station: rail,
              },
            ];
      const siteTargets: readonly (readonly [number, AutoMovieVector2Tuple])[] =
        name === "arm"
          ? ARM.filter(([key]): boolean => key !== "wrist").map(
              ([key, s]): readonly [number, AutoMovieVector2Tuple] => [
                s,
                ratio(complete().arm[key], zero.arm[key]),
              ],
            )
          : name === "leg"
            ? [
                ...LEG.map(([key, s]): readonly [number, AutoMovieVector2Tuple] => [
                  s,
                  ratio(complete().leg[key], zero.leg[key]),
                ]),
                [
                  EXTREMITIES.foot,
                  ratio(complete().extremities.foot, zero.extremities.foot),
                ],
              ]
            : [];
      for (const [s, scale] of siteTargets)
        if (
          s >= minimumRail &&
          s <= maximumRail &&
          (scale[0] !== rootRatio[0] || scale[1] !== rootRatio[1])
        )
          throw new Error(
            name +
              ": independent caliper site conflicts with the complete root interval at " +
              s,
          );
      maps.set(prior.name, { forward });
      generated.set(
        name,
        Native.create({
          original: prior,
          bone: placed,
          originals,
          axis,
          scale: scales,
          station: forward,
          features,
          ...(course === undefined ? {} : { authority: { sources: rootTargets,
            ...(course.axis === skin ? {} : { sampling: {
              maximumSpeed: course.maximumSpeed, materialBreaks: course.materialBreaks,
            } }),
          } }),
          protection: [
            ...requirements.map(
              (requirement): Native.ISpec["protection"][number] => ({
                sources: rootTargets,
                requirement,
              }),
            ),
            ...measured(prior, axis, features, siteTargets),
          ],
        }),
      );
    } catch (error: unknown) {
      rootFailures.push(
        name + ": " + (error instanceof Error ? error.message : String(error)),
      );
    }
  }
  if (rootFailures.length > 0)
    throw new Error(
      "native shared-root source admission failed:\n" + rootFailures.join("\n"),
    );

  const seedControls: Map<string, IAutoMovieHumanF1NativeRoot.ISeedTransport> = new Map();
  /** Issue the original search or named material point from this same root/source owner. */
  function nativeSeed(
    family: IAutoMovieHumanConicLoft.IFamily,
    seed: IAutoMovieHumanF1NativeRoot.ISeed,
    hostFace: string,
  ): IAutoMovieConstructionSeed {
    const port: string = family.name.startsWith(original.nostril.name) ? original.body.nose.name : "";
    const spec: IAutoMovieHumanF1NativeRoot.IRootSpec | undefined = rootPorts.get(port);
    const before: IAutoMovieViewPart | undefined = originals.get(family.name);
    if (spec === undefined || before === undefined)
      throw new Error("dependent cutter has no shared original root/source: " + family.name);
    const host: IAutoMovieHumanConicLoft.IFamily | undefined = port === original.body.nose.name
      ? generated.get("nose") : undefined;
    const result: Contact.IResult = Contact.create(
      spec, before, H.source(family), seed, hostFace,
      host === undefined ? undefined : H.source(host),
    );
    seedControls.set(family.name, result.observation);
    return result.seed;
  }
  /** Every native port reads the same resolved original-control root definition. */
  function rootLoop(
    name: "arm" | "breast" | "nose",
    side: 1 | -1,
  ): IAutoMovieConstructionPortLoop {
    const key: string = original.body[name].name + (side < 0 ? ".mirror" : "");
    const spec: IAutoMovieHumanF1NativeRoot.IRootSpec | undefined = rootPorts.get(key);
    if (spec === undefined)
      throw new Error("shared root definition absent: " + key);
    return spec.loop;
  }
  return { rootPorts, rootPrepared, rootLoop, nativeSeed, seedControls };
}

/** Original root calibration shared by all complete native candidates. */
export namespace AutoMovieHumanF1NativeRoots {
  /** The original nose correspondence, or its unchanged source-admission cause. */
  export type NoseCalibration =
    | {
        /** A complete original nose correspondence and its level support. */
        readonly calibration: IAutoMovieHumanF1NativeRoot.ICalibration;
      }
    | {
        /** Cause reported with the other root failures during full assembly. */
        readonly refusal: string;
      };

  /** Prepare the nose's original port and rail once at the complete assembly scope. */
  export function calibrateNose(
    original: IAutoMovieHumanF1.IAssembly,
    originals: ReadonlyMap<string, IAutoMovieViewPart>,
    size: ISize,
  ): NoseCalibration {
    const prior: IAutoMovieHumanConicLoft.IFamily = original.body.nose;
    try {
      const part: IAutoMovieViewPart | undefined = originals.get(prior.name);
      const parent: IAutoMovieViewPart | undefined = originals.get(original.body.trunk.name);
      if (part === undefined || parent === undefined)
        throw new Error("original port source absent: " + (part === undefined ? prior.name : original.body.trunk.name));
      const loop: IAutoMovieConstructionPortLoop = original.roots.nose;
      const count: number | undefined = loop.shape?.length;
      if (count === undefined)
        throw new Error("original root needs its explicit column controls: " + prior.name);
      const from: number = prior.knots[0]!;
      const station: number = from + RAIL.nose;
      return {
        calibration: Root.calibrate({
          name: prior.name,
          parent,
          child: part,
          loop,
          rails: AutoMovieHumanF1RootRails.nose.map((distance: number): number => from + distance),
          count,
          correspondence: "length",
          metric: { station, ...size },
          basis: part.axis.at(station),
        }),
      };
    } catch (error: unknown) {
      return { refusal: error instanceof Error ? error.message : String(error) };
    }
  }
}
