import type { IAutoMovieScaffoldProps } from "./IAutoMovieScaffoldProps";
import { assertScaffoldProjectName } from "./assertScaffoldProjectName";
import { attachScaffoldSyncState } from "./attachScaffoldSyncState";
import { createScaffoldVariables } from "./createScaffoldVariables";
import { mergeScaffoldFiles } from "./mergeScaffoldFiles";
import { renderScaffoldInstructions } from "./renderScaffoldInstructions";
import { renderScaffoldLayer } from "./renderScaffoldLayer";

/**
 * Render a pnpm workspace root that holds several productions, into an in-memory `{ posixPath: content }` map.
 *
 * The map joins the shared instruction surface from {@link renderScaffoldInstructions} with the `workspace` layer: `pnpm-workspace.yaml` listing `movies/shorts/*`, `movies/series/*` and `packages/*` with named `catalogs` of the build-time `AUTOMOVIE_TEMPLATE_VERSIONS` ranges, grouped by `AUTOMOVIE_TEMPLATE_CATALOGS` with one anchor per release group, a root `package.json` named by the admitted name with the `automovie` CLI as a development dependency, its README and `.gitignore`. The generated instruction digests are added for explicit later sync. No production is included; {@link renderWorkspaceProductionScaffold} renders each one. Nothing is written.
 *
 * @param props The workspace's name, admitted by {@link assertScaffoldProjectName}.
 * @returns The rendered file map.
 * @throws When the name is refused, when a layer or the shared-skill directory is missing, on a placeholder refusal, on a token error, or on a path collision within or between layers.
 *
 * @evidence contracts/development/implementation.md#principled-implementation The root catalog is rendered from the same version table that a single production's dependencies use, so a workspace production's `catalog:` specifiers resolve to the ranges this package was built with.
 * @evidence contracts/development/implementation.md#clear-and-simple-structure The function chooses the layers and token values; name admission, layer rendering, joining and sync state each have one owner.
 * @evidence contracts/development/implementation.md#prohibited-implementation-shortcuts The workspace layer is ordinary scaffold content rendered with the shared tokens; nothing is generated by string assembly here.
 * @evidence contracts/development/common.md#meaningful-documentation The comment states the joined layers, what the workspace layer contains, the added state, what is excluded, and what throws.
 * @evidence contracts/development/implementation.md#efficient-algorithms Two layer renders, one join pass and one digest per instruction file.
 * @evidenceExclude contracts/development/implementation.md#reuse-equivalent-work Each call reads the scaffold as installed now and is made once per CLI run.
 * @evidence contracts/development/implementation.md#bound-retention-and-release-resources Reads close before returning, and the returned map is owned by the caller.
 */
export const renderWorkspaceScaffold: (
  props: IAutoMovieScaffoldProps,
) => Record<string, string> = (
  props: IAutoMovieScaffoldProps,
): Record<string, string> =>
  attachScaffoldSyncState(
    mergeScaffoldFiles(
      renderScaffoldInstructions(),
      renderScaffoldLayer(
        "workspace",
        createScaffoldVariables({
          name: assertScaffoldProjectName(props.name),
          skills: ".agents/skills",
          dependencies: "release",
        }),
      ),
    ),
  );
