import { createHash } from "node:crypto";
import path from "node:path";

import type { IScaffoldSyncPlan } from "./IScaffoldSyncPlan";
import type { IScaffoldSyncProps } from "./IScaffoldSyncProps";
import { SCAFFOLD_SYNC_STATE_FILE } from "./SCAFFOLD_SYNC_STATE_FILE";
import { isScaffoldInstruction } from "./isScaffoldInstruction";
import { readScaffoldSyncFile } from "./readScaffoldSyncFile";
import { renderScaffold } from "./renderScaffold";

/**
 * Plans a complete instruction sync without changing the production.
 *
 * @evidence contracts/common.md#principled-implementation Current LF digests are compared with desired content and the stored or explicit prior baseline; all conflicts are collected before publication.
 * @evidence contracts/common.md#clear-and-simple-design The planner owns three-way comparison while rendering owns bundled inputs and publication owns writes.
 * @evidence contracts/common.md#prohibited-implementation-shortcuts No contracts, canon, reviews, project/configuration files or custom skills absent from the bundle are overwritten. Unknown legacy differences conflict instead of becoming guessed generated bytes.
 * @evidence contracts/common.md#meaningful-documentation The plan records changed/unchanged/conflicting/retired paths, exact write preconditions and a state file placed last.
 * @evidence contracts/performance.md#efficient-algorithms Rendering and per-file reads/hash scans scale with bundle and existing instruction bytes, plus deterministic path ordering; no whole production body is scanned.
 * @evidence contracts/performance.md#reuse-equivalent-work Each file observation and digest is reused inside the plan; returned plans are not accepted as later filesystem proof by a separate apply API.
 * @evidence contracts/performance.md#bound-retention-and-release-resources The plan owns candidate text and snapshots; input reads close synchronously, and no background work or cross-call cache is retained.
 */
export function planScaffoldSync(props: IScaffoldSyncProps): IScaffoldSyncPlan {
  const location: string = path.resolve(props.location);
  const bundle: Record<string, string> = renderScaffold({ name: props.name });
  const state: ReturnType<typeof readScaffoldSyncFile> = readScaffoldSyncFile(
    location,
    SCAFFOLD_SYNC_STATE_FILE,
  );
  const previous: Record<string, string> =
    state === undefined ? {} : parseState(state.text);
  const plan: IScaffoldSyncPlan = {
    location,
    files: {},
    expected: {},
    changed: [],
    unchanged: [],
    conflicts: [],
    retired: [],
  };
  const desired: Record<string, string> = {};
  for (const [relative, content] of Object.entries(bundle)) {
    if (!isScaffoldInstruction(relative)) continue;
    desired[relative] = digest(content);
    const current: ReturnType<typeof readScaffoldSyncFile> =
      readScaffoldSyncFile(location, relative);
    if (current !== undefined && digest(current.text) === desired[relative]) {
      plan.unchanged.push(relative);
      continue;
    }
    const baseline: string | undefined =
      previous[relative] ??
      (props.baseline === undefined
        ? undefined
        : priorDigest(props.baseline, relative));
    if (current !== undefined && digest(current.text) !== baseline) {
      plan.conflicts.push(relative);
      continue;
    }
    plan.changed.push(relative);
    plan.files[relative] = content;
    plan.expected[relative] = current?.snapshot ?? null;
  }
  plan.retired = Object.keys(previous).filter(
    (relative: string): boolean => !(relative in desired),
  );
  const next: string =
    JSON.stringify(
      { version: 1, files: { ...previous, ...desired } },
      null,
      2,
    ) + "\n";
  // State is last: a stopped content publication must not advance its baseline.
  if (state?.text !== next) {
    plan.files[SCAFFOLD_SYNC_STATE_FILE] = next;
    plan.expected[SCAFFOLD_SYNC_STATE_FILE] = state?.snapshot ?? null;
  }
  return plan;
}

/** Canonical line endings avoid treating checkout conversion as a local edit. */
function digest(text: string): string {
  return createHash("sha256")
    .update(text.replaceAll("\r\n", "\n"))
    .digest("hex");
}

/** Read the caller's explicit prior adopted instruction file without changing it. */
function priorDigest(root: string, relative: string): string | undefined {
  const source: ReturnType<typeof readScaffoldSyncFile> = readScaffoldSyncFile(
    root,
    relative,
  );
  return source === undefined ? undefined : digest(source.text);
}

/** Refuse malformed state and any path outside the generated instruction surface. */
function parseState(text: string): Record<string, string> {
  const state: unknown = JSON.parse(text);
  if (
    typeof state !== "object" ||
    state === null ||
    !("version" in state) ||
    state.version !== 1 ||
    !("files" in state) ||
    typeof state.files !== "object" ||
    state.files === null ||
    Array.isArray(state.files)
  )
    throw new Error("Invalid scaffold sync state.");
  const files: Record<string, string> = {};
  for (const [relative, value] of Object.entries(state.files)) {
    if (
      !isScaffoldInstruction(relative) ||
      typeof value !== "string" ||
      !/^[0-9a-f]{64}$/u.test(value)
    )
      throw new Error("Invalid scaffold sync baseline: " + relative);
    files[relative] = value;
  }
  return files;
}
