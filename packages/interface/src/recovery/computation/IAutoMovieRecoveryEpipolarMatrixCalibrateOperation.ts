import type { IAutoMovieRecoveryCameraChartCreationOperation } from "../../index";

/**
 * Project a pixel fundamental matrix onto the supplied-calibration essential
 * manifold and return all four relative-pose candidates. Arrays are row-major;
 * each candidate maps first-camera coordinates to second-camera coordinates.
 * Translation has unit norm and carries no physical length measurement. The
 * equal-singular projection and four-pose ambiguity follow HZ chapter 9:
 * https://www.robots.ox.ac.uk/~vgg/hzbook/hzbook2/HZepipolar.pdf
 */

export namespace IAutoMovieRecoveryEpipolarMatrixCalibrateOperation {
  /**
   * Project a pixel fundamental matrix onto the supplied-calibration essential
   * manifold and return all four relative-pose candidates. Arrays are
   * row-major; each candidate maps first-camera coordinates to second-camera
   * coordinates. Translation has unit norm and carries no physical length
   * measurement. The equal-singular projection and four-pose ambiguity follow
   * HZ chapter 9:
   * https://www.robots.ox.ac.uk/~vgg/hzbook/hzbook2/HZepipolar.pdf
   */

  export type Operation = (
    fundamental: readonly number[],
    first: ReturnType<IAutoMovieRecoveryCameraChartCreationOperation.Operation>,
    second: ReturnType<IAutoMovieRecoveryCameraChartCreationOperation.Operation>,
    maxSweeps: number,
  ) => {
    /**
     * Row-major 3 by 3 calibrated essential matrix; translation is recoverable
     * only up to the admitted gauge.
     */
    essential: number[];

    /**
     * Row-major 3 by 3 fundamental matrix in the declared pixel charts;
     * homogeneous scale has no metric meaning.
     */
    fundamental: number[];

    /**
     * Relative discrepancy between the projected essential model and the
     * estimated epipolar model; dimensionless.
     */
    relativeProjectionDiscrepancy: number;

    /**
     * Candidate relative camera poses generated by the calibrated essential
     * decomposition.
     */
    poses: {
      /**
       * Row-major 3 by 3 camera rotation in the operation's declared
       * source-to-camera convention.
       */
      rotation: number[];
      /**
       * Camera translation in the operation's admitted reconstruction scale;
       * two-view direction alone has no metric length.
       */
      translation: [number, number, number];
    }[];
  };
}
