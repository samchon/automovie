
/**
 * Canonical converted motion result sealed by builder-owned digests.
 *
 * @evidence contracts/common.md#principled-implementation materializeGeneratedFiles selects the declared actor's compiled performance motion, hashes its canonical value and separately hashes the complete `shots/<encoded-shot>.json` candidate including its trailing LF. The result can include other enacted actions, rather than being the standalone adoption draft motion or a dedicated converted-motion file.
 * @evidence contracts/common.md#clear-and-simple-design Semantic motion identity is distinct from publication byte identity, allowing receipt verification to detect changed serialization without confusing it with which motion the actor enacts.
 * @evidence contracts/common.md#prohibited-implementation-shortcuts Source-asset digest is not reused as converted output identity, and a matching clip name cannot certify a different canonical motion or generated byte file.
 * @evidence contracts/common.md#meaningful-documentation Distinguishes actual compiled actor-motion identity from whole-shot serialized-byte identity and gives the generated-root-relative path boundary.
 * @author Samchon
 */
export interface IAutoMovieExternalMotionConversionResult {
  /** Stable project-native motion identity assigned to the result. */
  motionId: string;

  /** Canonical digest of the project-native motion value. */
  motionDigest: string;

  /** Compiled shot file path relative to the production's generated root. */
  outputPath: string;

  /** Content digest of the exact generated output file bytes. */
  outputDigest: string;
}
