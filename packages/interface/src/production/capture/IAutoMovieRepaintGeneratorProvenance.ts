/**
 * Descriptive metadata and cost basis for the generator behind repaint.
 *
 * The cost basis and production consumer accompany the selected runtime.
 *
 * @evidence contracts/common.md#principled-implementation Required cost and consumer fields carry authored adoption context, while optional source, license and terms date are strings; this type validates neither nonblank content nor credential-free locators.
 * @evidence contracts/common.md#clear-and-simple-design Required cost and consumer describe adoption context while optional metadata describes provenance, separate from runtime identity and execution policy.
 * @evidence contracts/common.md#prohibited-implementation-shortcuts Optional metadata is not a verified license or terms-review receipt; no retained host validates or preserves this context in generated bytes.
 * @evidence contracts/common.md#meaningful-documentation Defines optional descriptive fields, explicit cost basis and typed production consumer with an authored adoption reason.
 * @author Samchon
 */
export interface IAutoMovieRepaintGeneratorProvenance {
  /** Optional descriptive source location. */
  source?: string;

  /** Optional descriptive license metadata. */
  license?: string;

  /** Optional descriptive date metadata. */
  termsCheckedAt?: string;

  /** Authored cost basis, including an explicit local-compute basis. */
  cost: string;

  /** Typed production consumer and authored reason for this adoption. */
  consumer: {
    /** Exact generated-content lane. */
    kind: "repaint";

    /** Why this production needs a repainted appearance rendition. */
    reason: string;
  };
}
