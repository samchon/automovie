/**
 * Compatibility characterization retained separately from the user decision.
 *
 * @evidence contracts/common.md#principled-implementation resolveExternalMotionClips emits compatible for adopted native or usable retargeted motion, retaining retarget warning paths and messages as findings; failed structural or ROM admission produces no adopted clip or conversion receipt.
 * @evidence contracts/common.md#clear-and-simple-design One status and ordered finding list summarize analysis while transformation details and any explicit losses remain separate receipt groups.
 * @evidence contracts/common.md#prohibited-implementation-shortcuts Override-required and incompatible currently have no receipt producer or implemented override workflow. Usable physics warnings remain findings with an empty loss list rather than fabricated unauthorized semantic losses.
 * @evidence contracts/common.md#meaningful-documentation Defines analysis-versus-user-decision ownership, the ordered finding list and the absence of an implemented authorization effect for override-required.
 * @author Samchon
 */
export interface IAutoMovieExternalMotionReceiptCharacterization {
  /** Compatibility analysis status; override-required is a recorded classification, not an implemented user-approval workflow. */
  status: "compatible" | "override-required" | "incompatible";

  /** Deterministically ordered source-to-target compatibility findings. */
  findings: string[];
}
