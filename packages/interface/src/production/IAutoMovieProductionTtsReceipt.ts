import type { IAutoMovieProductionLipSyncJoin } from "./IAutoMovieProductionLipSyncJoin";
import type { IAutoMovieProductionPhonemeChunk } from "./IAutoMovieProductionPhonemeChunk";
import type { IAutoMovieProductionViseme } from "./IAutoMovieProductionViseme";

/**
 * Receipt of one generated dialogue line, adopted as fixed bytes with
 * provenance.
 *
 * The product writes no speech: a production generates its line with a speech
 * model of its choice, stores the mono 32-bit float WAVE file, and records this
 * receipt beside it. Ingest's `admitProductionTtsReceipt` admits the receipt
 * against its line and those bytes before any mix reads them. Version 6
 * receipts cannot be converted, because they lack `text` and
 * `inferenceArguments`; record such a line again.
 */
export interface IAutoMovieProductionTtsReceipt {
  /** Receipt schema. */
  version: 7;

  /** Exact dialogue line id the receipt was generated for. */
  line: string;

  /** Exact text sent to the generator, which must equal the line's text. */
  text: string;

  /**
   * Content address of the request: `sha256:` and the lowercase SHA-256 of the
   * UTF-8 bytes of `[text, model, modelRevision, conditioning,
   * inferenceArguments]` encoded as automovie.canonical-json.v2 (engine's
   * `canonicalizeAutoMovieJson`: object keys sorted by code unit, no
   * whitespace). Admission recomputes it and refuses a receipt whose stored key
   * differs.
   */
  cacheKey: string;

  /** Generator model identity, such as a model repository name. */
  model: string;

  /**
   * Immutable revision of the generator model, such as a commit hash or a
   * weights digest.
   */
  modelRevision: string;

  /** How the generator was told whose voice to speak in. */
  conditioning: IAutoMovieProductionTtsReceipt.IConditioning;

  /**
   * Every inference argument the generator call received, such as speed,
   * temperature or seed.
   */
  inferenceArguments: Record<string, string | number | boolean>;

  /**
   * Generator cost basis and consumer retained with the generated bytes.
   *
   * The record accompanies the exact runtime and synthesized line.
   */
  generatorProvenance: {
    /** Optional descriptive source location. */
    source?: string;

    /** Optional descriptive license metadata. */
    license?: string;

    /** Optional descriptive date metadata. */
    termsCheckedAt?: string;

    /** Authored cost basis, including an explicit local-compute basis. */
    cost: string;

    /** Typed production consumer and authored reason for this adoption. */
    consumer: {
      /** Exact generated-content lane. */
      kind: "dialogue-synthesis";

      /** Why this production needs synthesized dialogue from this generator. */
      reason: string;
    };
  };

  /**
   * UTC instant captured immediately before the generator call that produced
   * this receipt's immutable PCM.
   */
  generatedAt: string;

  /**
   * Model-native sample rate in samples per second, a positive safe integer;
   * the WAVE file declares the same rate.
   */
  sourceSampleRate: number;

  /**
   * Exact mono sample count of the WAVE file at `sourceSampleRate`, a positive
   * safe integer.
   */
  sourceSamples: number;

  /**
   * `sha256:` and the lowercase SHA-256 of the WAVE file's samples as
   * little-endian Float32 bytes, which is its `data` chunk.
   */
  pcmDigest: string;

  /** Optional phoneme stream in synthesis order, when the generator returns one. */
  phonemes?: string;

  /**
   * Optional IPA phoneme chunks on the model-native sample clock, in order,
   * each nonempty and within `[0, sourceSamples]`, none overlapping or
   * preceding the previous one. A speech model's own chunks, or one phoneme per
   * chunk from forced alignment when `aligner` is present. Absent, the line
   * drives its speaker's jaw from its loudness.
   */
  phonemeChunks?: IAutoMovieProductionPhonemeChunk[];

  /**
   * Forced aligner that produced `phonemeChunks` from the adopted bytes and
   * text; absent when the chunks are the speech model's own.
   */
  aligner?: {
    /** Aligner model identity. */
    model: string;

    /** Immutable revision of the aligner model. */
    revision: string;
  };

  /** Adapter, native backend, model-cache, and bundled-voice byte identity. */
  runtimeAssets: Array<{
    /** Stable package or revision-cache-relative asset name. */
    path: string;

    /** Digest of the exact bytes consumed by synthesis. */
    digest: string;
  }>;

  /**
   * Optional mouth targets a generator reported; the render derives its own
   * from `phonemeChunks`.
   */
  visemes?: IAutoMovieProductionViseme[];

  /**
   * Join from final-byte viseme timing to the authored speaking actor, when a
   * host recorded one.
   */
  lipSync?: IAutoMovieProductionLipSyncJoin;
}

/** Companion types of the dialogue receipt. */
export namespace IAutoMovieProductionTtsReceipt {
  /**
   * The generator's voice conditioning: a named voice the model ships, or
   * reference audio cloned under the production's own permission record.
   */
  export type IConditioning =
    | {
        /** A voice the model names. */
        mode: "voice";

        /** The model's voice name. */
        voice: string;
      }
    | {
        /** Reference audio conditions the voice. */
        mode: "reference-audio";

        /** `sha256:` digest of the exact reference audio bytes. */
        referenceDigest: string;

        /**
         * Verified transcript of the reference, when the generator was
         * conditioned on one.
         */
        transcript?: string;
      };
}
