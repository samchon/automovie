import { AutoMovieGuidePass } from "../cinematics/AutoMovieGuidePass";
import { IAutoMovieCaptureRuntimeIdentity } from "./IAutoMovieCaptureRuntimeIdentity";
import { IAutoMovieRenderBundleManifest } from "./IAutoMovieRenderBundleManifest";
import { AutoMovieRepaintReferenceRole } from "./capture/AutoMovieRepaintReferenceRole";
import { IAutoMovieRepaintParameters } from "./capture/IAutoMovieRepaintParameters";

/**
 * Attempt-scoped host input for repainting one verified deterministic shot with fixed reference bytes and exact authored controls.
 *
 * @evidence contracts/common.md#principled-implementation The production host resolves current deterministic bundle identity, verified PNG frames and digest-matched role-specific references before calling the adopted generator; the abort signal bounds one attempt's cancellation.
 * @evidence contracts/common.md#clear-and-simple-design Groups deterministic source, fixed references and authored parameters separately so an adapter receives the exact admitted inputs without choosing production assets or rewriting technical truth.
 * @evidence contracts/common.md#prohibited-implementation-shortcuts Generator adapters cannot substitute a stale source or collapse reference roles; successful generated bytes still owe candidate receipt, preservation and selection admission after this call.
 * @evidence contracts/common.md#meaningful-documentation Defines attempt cancellation, project and production identity, compile binding, exact source bytes and capture runtime, fixed reference roles and authored controls.
 * @author Samchon
 */
export interface IAutoMovieProductionRepaintInput {
  /** Attempt-scoped cancellation boundary. */
  signal: AbortSignal;

  /** Active project root. */
  projectRoot: string;

  /** Active production namespace. */
  productionId: string;

  /** Current builder-owned registry fingerprint. */
  compileFingerprint: string;

  /** Exact compiled shot id. */
  shot: string;

  /** Verified deterministic source identity and bytes. */
  source: {
    /** Project-relative content-addressed source bundle. */
    bundle: string;

    /** Verified source bundle manifest. */
    manifest: IAutoMovieRenderBundleManifest;

    /** Digest over the verified manifest and frame bytes. */
    fingerprint: string;

    /** Current decoded source frames. */
    frames: Array<{
      /** Frame index. */
      index: number;

      /** Shot-local frame time in seconds. */
      time: number;

      /** Beauty or structural pass. */
      pass: AutoMovieGuidePass;

      /** Exact PNG digest. */
      digest: string;

      /** Raw verified PNG bytes. */
      bytes: Uint8Array;
    }>;

    /** Capture runtime that produced the deterministic controls. */
    captureRuntime: IAutoMovieCaptureRuntimeIdentity;
  };

  /** Verified fixed reference bytes. */
  references: Array<{
    /** Exact non-collapsible role; `character` means identity. */
    role: AutoMovieRepaintReferenceRole;

    /** Project-relative asset-manifest path. */
    path: string;

    /** Current digest. */
    digest: string;

    /** Current bytes. */
    bytes: Uint8Array;
  }>;

  /** Exact generation controls. */
  parameters: IAutoMovieRepaintParameters;
}
