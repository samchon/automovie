import { Frame } from "./Frame";
import { Vec } from "./Vec";

/** Convert the orthonormal frame columns to a unit quaternion. */

export const rotationOf = (u: Vec, v: Vec, n: Vec): Frame["rotation"] => {
  const [m00, m10, m20] = u, [m01, m11, m21] = v, [m02, m12, m22] = n;
  const trace = m00 + m11 + m22;
  let x: number, y: number, z: number, w: number;
  if (trace > 0) {
    const s = 2 * Math.sqrt(trace + 1);
    w = s / 4;
    x = (m21 - m12) / s;
    y = (m02 - m20) / s;
    z = (m10 - m01) / s;
  } else if (m00 > m11 && m00 > m22) {
    const s = 2 * Math.sqrt(1 + m00 - m11 - m22);
    w = (m21 - m12) / s;
    x = s / 4;
    y = (m01 + m10) / s;
    z = (m02 + m20) / s;
  } else if (m11 > m22) {
    const s = 2 * Math.sqrt(1 + m11 - m00 - m22);
    w = (m02 - m20) / s;
    x = (m01 + m10) / s;
    y = s / 4;
    z = (m12 + m21) / s;
  } else {
    const s = 2 * Math.sqrt(1 + m22 - m00 - m11);
    w = (m10 - m01) / s;
    x = (m02 + m20) / s;
    y = (m12 + m21) / s;
    z = s / 4;
  }
  const norm = Math.hypot(x, y, z, w);
  return { x: x / norm, y: y / norm, z: z / norm, w: w / norm };
};
